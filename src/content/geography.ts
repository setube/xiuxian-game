/**
 * 京城。不属任何州，皇室生在这里。
 *
 * 正式名称就叫「京师」，不另造一个「天启」「景都」式的两字专名。
 * 明代北京在制度上就叫京师（永乐十九年改北京为京师，正统年间重定），
 * 民间说「京城」「城里」「京里」——正文里那些「迁出京城」照旧，
 * 门牌上是「京师」。这样**年号和地名彻底分开**：「景和十六年，京师。」
 * 从前那个「天启」既是熹宗的年号又像一座城的名字，两条线搅在一起。
 *
 * 哪天写迁都、两京、行在，才让这个称号随世界事件变——比每一世随机一个
 * 首都名有价值得多。
 */
export const CAPITAL = '京师 · 皇城'

