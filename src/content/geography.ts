/**
 * 地理。
 *
 * 一条大江自西向东，贯穿数州，沿岸设府。这不是装饰性的设定，
 * 是一条硬约束——收尾那一卷靠「渡口」和「江面」立住，
 * 所以每一个府都必须临水。古时设府本来也多在漕运要冲上，
 * 这一条既省事又不假。
 *
 * 州府和乡里是分开的：`PREFECTURES` 管到府，出身管到街巷。
 * 两边组合，一个农家子就可能生在江陵府的杏花坞，
 * 也可能生在东莱府的下河屯——而不是所有人都挤在临江府。
 */
export interface Prefecture {
  /** 州 */
  province: string
  /** 府 */
  name: string
  /** 掷中的相对权重。大府人多，小府人少 */
  weight: number
}

