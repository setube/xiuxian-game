/**
 * 教法。
 *
 * 这一格是这一版新长出来的那一维，而它长出来的过程值得记一笔：
 * 它不是先想到「应该有个教法维度」再去填内容的。
 * 是先有了陶仲——他后山认草那一段写着「说了名字，说完就走，
 * 不管你记没记住」，门槛上那一段写着念完五句就起身收拾去了。
 * **他的教法早就在内容里了，只是从来没有被命名过。**
 *
 * 四种教法不是四个档位，没有高下。它们是四种不同的东西，
 * 各自能送到的地方不一样：
 *
 *     说给你听　　念一遍口诀，讲一遍道理。你听着
 *     做给你看　　他做一遍，你在旁边看着
 *     按着你做　　他上手扳你的肩、按你的背。你身上有他的手印
 *     让你自己找　他把你放在那儿，什么也不说。这也是一种教
 */
export type Way = '说给你听' | '做给你看' | '按着你做' | '让你自己找'

export const WAYS: readonly Way[] = ['说给你听', '做给你看', '按着你做', '让你自己找']

