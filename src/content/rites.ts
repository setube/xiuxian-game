import type { AttributeKey } from '@/types/game'

/**
 * 他教的那一点东西。
 *
 * ## 这一册回答的是：「他教了你」和「你真的会了」之间隔着什么
 *
 * 上一版这一册的答案是「隔着三道关口」——背得下来看记性，明白看悟性，
 * 转得动看根骨。三个数值题串起来，仍旧是数值题，只是串得长了些。
 *
 * 让这门具体的功法自己说话，答案是两样，而**两样都不在属性表里**：
 *
 *     你走的是不是那件事　　他能给你的只有话。而那件事不在话里
 *     你身上有没有那个东西　这一样练一辈子也补不了
 *
 * ## 这不是一条阶梯
 *
 * 原先四层排成一列：听过 → 记住 → 明白 → 转得动。排得整整齐齐，
 * 而**那个整齐是命名出来的，不是这门功法长出来的**。
 * 「转得动」根本不是「明白」的下一级——它是另一条轴上的事：
 * 前三层是脑子里的，最后一层是身上的。一个人完全可能背得滚瓜烂熟、
 * 每一句都讲得出道理，身上一丝反应也没有；也完全可能身上早有反应了，
 * 却说不出那是怎么回事。
 *
 * 所以这一版是两条轴，各走各的：
 *
 *     脑子里　听过 → 记住 → 明白　　　　　　　　　见 `Grasp`
 *     身　上　没上手 →〔照着做 | 走岔了〕→ 摸着了 → 拿得住　见 `Hold`
 *
 * 第二条轴中间那个分叉是这一版全部的新东西，下面单说。
 *
 * ## 那个分叉：他以为他在教，他其实在挡路
 *
 * 陶仲的教法是「说给你听」——念五句，念完起身收拾去了，不看你做。
 * 而守一要的是「让你自己找」：那个数三下的地方在你身体里面，
 * **没有人能指给你看，也没有人能替你按。**
 *
 * 两样对不上。于是那五句话给了你一个错的方向感：
 * 你以为你知道该往哪儿使劲了，你很认真地往那儿使劲，
 * 而那不是那件事。这就是「走岔了」。
 *
 * 一个从没人教、自己瞎坐的人反倒不会走岔——他知道自己什么都不知道。
 * **认真教反而害了他**，这是这一册最不像游戏的一句话。
 *
 * 但教学不是白教的。走岔了还有一条出路，而且只有这一条：
 * **你自己把那五句想明白。** 那五句既是让他走岔的原因，
 * 也是他唯一能走出来的凭据——而多数人读不懂那张地图。
 *
 * ## 「照着做」和「走岔了」，正文里写的是同一段话
 *
 * 这是上一版那条纪律（「明白」这一关成败同文）的第二次应用，
 * 而且这一次更狠：不是同一关的成败共用一段话，是**两个完全不同的状态**
 * 共用一段话。方向对但还没碰着的人，和方向根本错了的人，
 * 看见的是同一件事——胸口有点发闷，你想大概是坐久了。
 *
 * `scripts/mastery.ts` 会逐字比对这两格，不一样就红。
 *
 * ## 「学会」不等于「属性涨了」
 *
 * 走完全程，属性表一格不动。四格各有各的可观察结果，全在 `holds` 里：
 *
 *     走岔了　　你照着做了几遍，只觉得胸口发闷
 *     摸着了　　数到第三下的时候，脐下那一处忽然凉了一下
 *     拿得住　　你已经不数那三下了。它自己会停
 *
 * 顺带说一句上一版留下的证据：「摸着了」那三行是从旧的 `转得动.passed`
 * 原封搬过来的，一个字没改。**那段文本描述的从来就不是「掌握」，
 * 是「碰着了一次」**——文本没写错，是名字起错了。
 */

