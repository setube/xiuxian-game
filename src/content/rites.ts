import type { AttributeKey } from '@/types/game'

/**
 * 他教的那一点东西。
 *
 * ## 这一册回答的是：教了，然后呢
 *
 * 从前「获得功法」是一行——背包里多一件东西，从此这个人会了。
 * 那一行把四件完全不同的事压成了一件：
 *
 *     听过口诀　　　他念了一遍，你在场
 *     背得下来　　　你能一字不差地重说一遍
 *     明白它说什么　你知道「脐下三寸」指的是哪儿、为什么要数三下
 *     转得动　　　　你照着做，身上真的有反应
 *
 * 四件事各有各的关口，**而且过不过得去看的不是同一样东西**。
 * 背得下来看记性，明白看悟性，转得动看的是根骨和神魂——
 * 于是一个记性极好、悟性也不差的孩子完全可能把口诀背得滚瓜烂熟、
 * 每一句都讲得出道理，**然后一辈子也没有转起来过**。
 *
 * ## 前两关补得了，第三关补不了
 *
 * 这是这一册全部的重量所在：
 *
 *     记住　　　练得多就背得下来。次数是有用的
 *     明白　　　练得多也能想通，只是慢得多。次数还是有用的
 *     转得动　　根骨不够，练一万遍也是零。**次数在这一关一点用也没有**
 *
 * 药庐那位挑人挑的是「肯不肯守着」，而肯守着确实能把前两关磨过去。
 * 他这辈子验证过很多次，次次都对。他没验证过的是第三关——
 * **他前半句是对的，后半句是错的，而这个区别他大概想不明白。**
 *
 * ## 玩家分不出的只有中间那一层
 *
 * 背没背下来，他自己清楚。转没转起来，他身上有没有反应，也清楚。
 * 唯独「明白了没有」——他以为自己明白了。
 *
 * 所以 `sights` 里 `明白` 这一关的成与败**写的是同一段话**。
 * 那不是偷懒，那是这一层的全部意思：
 * 「我觉得我懂了」和「我真的懂了」，人自己分不出来。
 */

/** 从底下往上数。一次最多过一关 */
export type Grasp = '听过' | '记住' | '明白' | '转得动'

export const GRASPS: readonly Grasp[] = ['听过', '记住', '明白', '转得动']

/**
 * 一关。
 *
 * `by` 是这一关看的那几样东西按权重合起来的分。`needs` 是坎。
 * `helps` 是练一次能补多少——**写 0 就是补不了**，
 * 那一关只看你生下来是什么样。
 */
export interface Gate {
  by: Partial<Record<AttributeKey, number>>
  needs: number
  /** 每多练一回往上加多少分。0 = 次数在这一关一点用也没有 */
  helps: number
}

/** 一关过了和没过，玩家各看见什么 */
export interface Sight {
  passed: readonly string[]
  failed: readonly string[]
}

export interface Rite {
  id: string
  name: string
  /** 教它的人怎么称呼它。玩家听见的是这个，不是 name */
  calls: string
  /** 他念的那几句。玩家看得见的全部就是这些 */
  words: readonly string[]
  /** 背得下来这一关 */
  remembering: Gate
  /** 明白它说什么这一关 */
  grasping: Gate
  /** 真的转得动这一关 */
  turning: Gate
  sights: Record<Grasp, Sight>
}

/**
 * 守一。
 *
 * 最粗浅的一样东西——粗浅到药庐那位教出去的时候一点也不心疼，
 * 粗浅到宗门里没有一个人会把它写进功法录。
 *
 * 可它是这个人一生中拿到的第一样真东西。
 *
 * ## 最后一句是「明白」那一关的关口
 *
 * 「你要找的不是气，是那个数三下的地方。」
 * 前面四句是动作，照着做就行，背下来也不难。这一句是道理，
 * 而**它听上去像是在说反话**。悟性不够的人会把它当成一句玄虚，
 * 背得很熟，从来没往心里去。
 */
export const QUIET_BREATH: Rite = {
  id: 'quiet-breath',
  name: '守一',
  calls: '一个呼吸法',
  words: [
    '「坐下。背直，别靠墙。」',
    '「气从鼻子进来，走到脐下三寸，停住。」',
    '「停住的时候数三下。不许多，也不许少。」',
    '「然后放出去。放的时候什么也不要想。」',
    '「记住——你要找的不是气，是那个数三下的地方。」',
  ],
  /**
   * 五句话，不长。记性寻常的人练几回也就背下来了，
   * `helps: 5` 说的就是这个：这一关是可以靠笨办法磨过去的。
   *
   * ## `by` 里只有记性，没有心志
   *
   * 从前这一格写的是 `{ memory: 8, will: 2 }`，看着更周全——
   * 背东西本来就要肯反复念。可**肯不肯反复念已经是 `helps` 那一格在管的事**，
   * 再往 `by` 里塞一份 `will`，就是同一样东西数了两遍。
   *
   * 数两遍的后果是实打实的：陶仲挑人挑的正是心志，
   * 于是**凡是他肯教的人，心志都不会低**，那两成 will 白送三十来分，
   * 34 的门槛谁也挡不住——「五句话背不下来」这种人生根本跑不出来。
   * 门禁 `scripts/tutelage.ts` 第五道就是撞在这上头才红的。
   */
  remembering: {
    by: { memory: 10 },
    needs: 44,
    helps: 5,
  },
  /**
   * 悟性那一关。`helps: 3` ——想得久也能想通，只是慢一半。
   *
   * 门槛压在 46 不是为了挡人，是为了让「背得下来却没往心里去」
   * 成为一种常见的人生，而不是一个稀罕的失败。
   */
  grasping: {
    by: { insight: 9, memory: 1 },
    needs: 46,
    helps: 3,
  },
  /**
   * **`helps: 0`。这一行是整册书的那句话。**
   *
   * 根骨六成、神魂四成，凑不够 55 就是凑不够。你可以背一辈子，
   * 可以每一句都讲得出道理，可以卯时起来风雨无阻地坐三年——
   * 那个数三下的地方不会有任何反应。
   *
   * 而且**没有人会告诉你是这个原因**。药庐那位只会觉得
   * 是不是自己教得不够细，玩家只会觉得是自己不够用功。
   */
  turning: {
    by: { root: 6, spirit: 4 },
    needs: 55,
    helps: 0,
  },
  sights: {
    听过: {
      passed: ['你把那五句在心里默了一遍，只记住了三句半。'],
      failed: ['你把那五句在心里默了一遍，只记住了三句半。'],
    },
    记住: {
      passed: [
        '这天夜里你忽然发觉，那五句你已经一个字也不会错了。',
        '你不记得自己是什么时候背下来的。',
      ],
      failed: ['你又默了一遍。中间那一句怎么也接不上，只好从头再来。'],
    },
    /**
     * 两边一字不差。这一关的成败玩家看不见，**这是有意的**。
     * `scripts/tutelage.ts` 会逐字比对这两段，不一样就红。
     */
    明白: {
      passed: [
        '你把那几句在心里过了一遍。',
        '「不是气，是那个地方。」',
        '你想，这话说得也没什么难懂的。',
      ],
      failed: [
        '你把那几句在心里过了一遍。',
        '「不是气，是那个地方。」',
        '你想，这话说得也没什么难懂的。',
      ],
    },
    转得动: {
      passed: [
        '数到第三下的时候，脐下那一处忽然凉了一下。',
        '很轻，一瞬就没了。你不敢动，坐着等它再来。',
        '它没有再来。可你知道你没有想错。',
      ],
      failed: ['天亮了。你什么也没有觉出来。'],
    },
  },
}

const ALL: readonly Rite[] = [QUIET_BREATH]

export function riteById(id: string): Rite | undefined {
  return ALL.find((one) => one.id === id)
}

export const RITES = ALL
