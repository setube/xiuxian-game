/**
 * 后来才明白的事。
 *
 * ## 这一册是「日志」和「回忆」的分界线
 *
 * 把每天发生的话原样存起来，那只是日志。几年以后翻开：
 *
 *     十三岁　今天帮家里收了一下午麦子。
 *     十五岁　今天帮家里收了一下午麦子。
 *     十七岁　今天帮家里收了一下午麦子。
 *
 * 单独看，一句意义也没有。
 *
 * 而这一册做的是另一件事：**让后来发生的事，回头给过去的普通日子
 * 重新赋予意义。** 它一个字也不改历史——
 *
 *     过去的事实　+　现在的新知识　=　新的解释
 *
 * 这跟认知系统里那条「多年以后才知道那是符书」是同一个结构：
 * 当年那句「你买了一册看不懂的书」没有变，变的是他现在怎么看它。
 *
 * ## 写新规则时的两条分寸
 *
 * 1. **`after` 不能太小。** 当场就明白的不叫「多年以后」，那叫当天的结果。
 *    这一层的全部价值在于隔了很久。
 * 2. **不要给每一天都配一句。** 一生中大多数普通日子就该一直普通下去——
 *    如果每一条日录最后都被点亮，那这个系统只是把「延迟发奖」做成了机制。
 */
