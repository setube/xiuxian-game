import type { Gender, Realm, Temper } from '@/types/game'

/**
 * 门口那几个人。
 *
 * ## 这一册回答的是：他终于找着人了，然后呢
 *
 * 从前找着人以后只有一句判决——摸一下腕子，说「不成」或者「跟上」。
 * 那一句背后是 `root >= 72`，玩家什么也不知道，也**什么也没发生**：
 * 他没见过这个人，没跟他说过话，事后连他姓什么都说不出。
 *
 * 这一册要的是那中间的一段：**两个人互相打量了一回。**
 *
 *     他怎么看你　　　拿他的尺子量你，量得准不准他自己也不知道
 *          ↕
 *     你怎么看他　　　你没有尺子。你只看得见衣裳、年纪、手
 *
 * 两边都会看错，而**两边都不知道自己看错了**。
 *
 * ## 他不是一台鉴定机
 *
 * 三个人三把尺子，各有各的边界：
 *
 *     山道上那个（炼气）　只看得见悟性和神魂。**他这辈子看不见资质。**
 *     观里那位（筑基）　　看得见资质了，可也只有七成准头
 *     后来遇上的长老　　　九成准，可他说出口的仍旧是「不错」两个字
 *
 * 所以「资质一般」这句话是谁说的，比这句话本身要紧得多——
 * 而玩家不知道这一点，他只听见一句「一般」。
 *
 * ## 玩家看他，看见的全是表象
 *
 * `sees` 里每一句都是真的：他看着很年轻、衣裳洗得发白、手上没有茧。
 * `reads` 是玩家从这些里读出来的意思，**而那些多半是错的**——
 * 看着年轻不代表年纪轻，衣裳旧不代表境界低。
 *
 * 这跟 `signs.ts` 里「征象 + 他自以为看懂的那句」是同一条纪律：
 * **世界给的那句不会错，他读出来的那句可能错。**
 */

/**
 * 玩家看见的一处，以及他从这一处读出来的意思。
 *
 * 分开写是这一层的全部要害。合成一句「你看出他是个高人」就完了——
 * 那句话既是观察也是结论，玩家没有出错的余地，
 * 而**没有出错余地的观察不叫观察，叫通知**。
 */
export interface Bearing {
  id: string
  /** 他确实看见了这个。世界事实，不会错 */
  sees: string
  /** 他从这一处读出来的意思。**可能是错的** */
  reads: string
  /**
   * 读错了没有，错在哪一类。
   *
   * `事实` 是把一件事本身认错了（以为他二十来岁）；
   * `因果` 是事情没认错、道理想歪了（以为衣裳旧所以本事不大）。
   * 不写就是这一处他恰好读对了——**而他同样不知道自己读对了。**
   */
  mistaken?: '事实' | '因果'
}

/**
 * 一个站在门口的人。
 *
 * `observer` 指的是 `observers.ts` 里那把尺子。两份数据分开放是有道理的：
 * **尺子是一类人共用的，而人是具体的一个。** 观里那位和多年后
 * 重新看你的那位可以共用「筑基修士」这把尺子，
 * 却是两个不同的人、两段不同的关系、两个不同的年份。
 */
export interface Cultivator {
  id: string
  surname: string
  given: string
  gender: Gender
  /** 比玩家早生多少年。他一百二十岁，看着三十 */
  bornBefore: number
  realm: Realm
  temper: Temper
  /** 玩家此刻会怎么称呼他。不是名字——名字要另外知道 */
  calls: string
  /** 他用哪把尺子看人。见 observers.ts */
  observer: string
  /** 他在哪儿 */
  place: string
  /** 玩家打量他的时候会注意到的几处 */
  bearing: readonly Bearing[]
  /**
   * 他量到多少分才肯多说两句。
   *
   * **读的是他量到的数，不是真值。** 一个看不见资质的人量到「悟性一般」，
   * 就到此为止了——哪怕站在他跟前的是万里挑一的胚子。
   *
   * 这一格是「他看错的后果是真的」那句话的落点：看错不只是说错一句话，
   * 是**他真的就那么待你了**，而你这辈子都不会知道为什么。
   */
  opensAt: number
  /** 他肯多说的时候，说的那几句 */
  opens: readonly string[]
  /** 他不肯多说的时候，是怎么打发你的 */
  closes: readonly string[]
}

