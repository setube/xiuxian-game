import type { Footing, Gender, Realm, Temper } from '@/types/game'

/**
 * 门口那几个人。
 *
 * ## 这一册回答的是：他终于找着人了，然后呢
 *
 * 从前找着人以后只有一句判决——摸一下腕子，说「不成」或者「跟上」。
 * 那一句背后是 `root >= 72`，玩家什么也不知道，也**什么也没发生**：
 * 他没见过这个人，没跟他说过话，事后连他姓什么都说不出。
 *
 * 这一册要的是那中间的一段：**两个人互相打量了一回。**
 *
 *     他怎么看你　　　拿他的尺子量你，量得准不准他自己也不知道
 *          ↕
 *     你怎么看他　　　你没有尺子。你只看得见衣裳、年纪、手
 *
 * 两边都会看错，而**两边都不知道自己看错了**。
 *
 * ## 他不是一台鉴定机
 *
 * 四个人四把尺子，各有各的边界：
 *
 *     山道上那个（炼气）　只看得见悟性和神魂。**他这辈子看不见资质。**
 *     观里那位（筑基）　　看得见资质了，可也只有七成准头
 *     药庐里那位（炼气）　**他压根不量资质**——他量的是肯不肯守着
 *     后来遇上的长老　　　九成准，可他说出口的仍旧是「不错」两个字
 *
 * 所以「资质一般」这句话是谁说的，比这句话本身要紧得多——
 * 而玩家不知道这一点，他只听见一句「一般」。
 *
 * ## 看得见，跟愿意，是两件事
 *
 * 这三个人还各自压着一句不说出口的话，见 `Stance`：
 *
 *     姜不换　　　他没在挑人。他那天只是路过
 *     秦守拙　　　他看得见，可他手上压着二十年前答应的一件事
 *     陶仲　　　　他愿意教，而**他挑人的那把尺子跟修行没有关系**
 *
 * 于是「能不能修仙」和「有没有人愿意教你」彻底分成两件事。
 * 玩家会把这两件事当成一件——他没有别的办法。
 *
 * ## 玩家看他，看见的全是表象
 *
 * `sees` 里每一句都是真的：他看着很年轻、衣裳洗得发白、手上没有茧。
 * `reads` 是玩家从这些里读出来的意思，**而那些多半是错的**——
 * 看着年轻不代表年纪轻，衣裳旧不代表境界低。
 *
 * 这跟 `signs.ts` 里「征象 + 他自以为看懂的那句」是同一条纪律：
 * **世界给的那句不会错，他读出来的那句可能错。**
 */

/**
 * 玩家看见的一处，以及他从这一处读出来的意思。
 *
 * 分开写是这一层的全部要害。合成一句「你看出他是个高人」就完了——
 * 那句话既是观察也是结论，玩家没有出错的余地，
 * 而**没有出错余地的观察不叫观察，叫通知**。
 */
export interface Bearing {
  id: string
  /** 他确实看见了这个。世界事实，不会错 */
  sees: string
  /** 他从这一处读出来的意思。**可能是错的** */
  reads: string
  /**
   * 读错了没有，错在哪一类。
   *
   * `事实` 是把一件事本身认错了（以为他二十来岁）；
   * `因果` 是事情没认错、道理想歪了（以为衣裳旧所以本事不大）。
   * 不写就是这一处他恰好读对了——**而他同样不知道自己读对了。**
   */
  mistaken?: '事实' | '因果'
}

/**
 * 他自己那一头的事。
 *
 * ## 为什么不能只有 `opensAt` 一个数
 *
 * `opensAt` 回答的是「他肯不肯多说两句」。这一节回答的是完全不同的问题：
 * **他凭什么在一个陌生孩子身上花工夫。**
 *
 * 三样东西各管各的，一样也不能省：
 *
 *     wants   他挑人的时候心里想的那件事。null = 他压根没在挑人
 *     ceiling 他肯到哪一步为止。**看得再上眼也过不去这道坎**
 *     bound   他身上已经压着的事。有这一条的人，那件事比你要紧
 *
 * `ceiling` 是这一节的要害。少了它，「他看出你是块料」就必然通向
 * 「所以他教你」——那样一来资质又变回了唯一的开关，
 * 只是从 `root >= 72` 换成了 `regard >= 72`，绕了一圈回到原地。
 *
 * 有了它，**「他看得见」和「他愿意」彻底分开**：
 * 观里那位看得清清楚楚，也照样只到「带一段」为止。
 * 而玩家永远听不到那个理由——他只会以为是自己不够好。
 */
export interface Stance {
  /** 他挑人的时候在意的那件事。写出来是给读代码的人看的，不参与计算 */
  wants: string | null
  /** 他肯走到哪一格为止 */
  ceiling: Footing
  /** 他身上压着的那件事。同样只是说明，不参与计算 */
  bound?: string
}

/**
 * 一个站在门口的人。
 *
 * `observer` 指的是 `observers.ts` 里那把尺子。两份数据分开放是有道理的：
 * **尺子是一类人共用的，而人是具体的一个。** 观里那位和多年后
 * 重新看你的那位可以共用「筑基修士」这把尺子，
 * 却是两个不同的人、两段不同的关系、两个不同的年份。
 */
export interface Cultivator {
  id: string
  surname: string
  given: string
  gender: Gender
  /** 比玩家早生多少年。他一百二十岁，看着三十 */
  bornBefore: number
  realm: Realm
  temper: Temper
  /** 玩家此刻会怎么称呼他。不是名字——名字要另外知道 */
  calls: string
  /** 他用哪把尺子看人。见 observers.ts */
  observer: string
  /** 他在哪儿 */
  place: string
  /** 玩家打量他的时候会注意到的几处 */
  bearing: readonly Bearing[]
  /**
   * 他量到多少分才肯多说两句。
   *
   * **读的是他量到的数，不是真值。** 一个看不见资质的人量到「悟性一般」，
   * 就到此为止了——哪怕站在他跟前的是万里挑一的胚子。
   *
   * 这一格是「他看错的后果是真的」那句话的落点：看错不只是说错一句话，
   * 是**他真的就那么待你了**，而你这辈子都不会知道为什么。
   */
  opensAt: number
  /** 他肯多说的时候，说的那几句 */
  opens: readonly string[]
  /** 他不肯多说的时候，是怎么打发你的 */
  closes: readonly string[]
  /** 他自己那一头的事。见 Stance */
  stance: Stance
  /**
   * 挪到某一格的时候他说的那句话。
   *
   * **台词属于人，不属于机制。** 同样是「使唤」这一格，
   * 观里那位说的是「把这几张纸抄一遍」，药庐那位说的是
   * 「这两日替我做件事」——差别不在档位上，在人身上。
   *
   * `ceiling` 以上不必写，那些格他永远走不到。反过来，
   * `ceiling` 以下缺一格就是个哑巴台阶，`scripts/verify.ts` 会当场红。
   */
  steps: Partial<Record<Footing, readonly string[]>>
  /** 他肯教的时候，教的是哪一样。没有这一格的人不会教任何人任何事 */
  teaches?: string
}

