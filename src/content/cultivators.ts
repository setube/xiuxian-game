const ALL: readonly Cultivator[] = [THE_ONE_ON_THE_PATH, THE_ONE_AT_THE_TEMPLE]

export function cultivatorById(id: string): Cultivator | undefined {
  return ALL.find((one) => one.id === id)
}

export const CULTIVATORS = ALL
