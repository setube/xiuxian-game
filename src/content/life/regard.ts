/**
 * 回村那一天。
 *
 * ## 这一卷是为了把一句旁白变成真的
 *
 * `exam.ts` 中秀才那一节里有这么一句，它在库里躺了很久：
 *
 * > 村里人见你改了称呼。有几个从前不太理你的，如今站住了说话。
 *
 * **而在这一卷之前，没有任何一个人真的改口。** `identity` 换成了「生员」，
 * 正文报了一句「改了称呼」，可库里每一处称呼照旧——16.md 点的正是这个：
 *
 * > 不能写死：`identity = 官员` → 所有人统一叫「大人」。
 * > 同一时刻可以存在多个称呼：邻居「张老爷」，旧友「三哥」，孩子「父亲」。
 *
 * ## 一句正文，两种人读出两种话
 *
 * 这一卷通篇只用两个记号，而它们是这一整层的全部：
 *
 *     {hail:谁}      那个人开口时怎么称呼你，连着后面的逗号
 *     mayAsk         那个人够不够格说这一档的话
 *
 * 同一句「{hail:east-wife}你可算回来了」，落到不同的人嘴里是：
 *
 *     邻家的妇人（没有边）　　「相公，你可算回来了。」
 *     家里的大人（十六年）　　「你可算回来了。」
 *
 * 后一句一个称呼也没有，而它比任何称呼都更说明两人的关系——
 * **中文里熟人开口本来就不带称呼**（见 `engine/address.ts` 的 `callMeBy`）。
 *
 * ## 而更要紧的是那句没问出口的话
 *
 * 16.md 里唯一一句加粗的话是：
 *
 * > **对话系统真正需要控制的不是「能不能出现这句话」，
 * > 而是「这个人凭什么能对你说这句话」。**
 *
 * 所以邻家那位妇人只说得出寒暄。她心里那句「你家往后是不是要起新屋了」
 * 是家常，而她跟你没有那份交情——`{ mayAsk: { who, how: '家常' } }`
 * 挡下的正是它。挡下之后正文写的不是「这句话不存在」，
 * 是**她站在那儿笑了笑，什么也没问**。
 *
 * 而同一句话，家里的大人张口就问。他不必够格，他本来就在那个位置上。
 *
 * ## 这一卷不给任何东西
 *
 * 没有属性、没有旗标、没有家底变化。中了秀才那一节该给的都给过了。
 * 这一卷只花掉一点时间，让那件事在**别人身上**发生一次。
 *
 * 一个人的身份变了，最先变的从来不是他自己。
 */
