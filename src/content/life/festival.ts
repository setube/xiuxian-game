import type { LifeEvent, SceneLibrary } from '@/types/game'

/**
 * 节令。
 *
 * ## 这一册跟别的册子差在哪：时令是它自己推的
 *
 * 一卷叫「中秋」的内容，说的是**到了八月十五**，不是**碰巧在八月十五**。
 * 这两句话的差别不是措辞，是这一册能不能被人读到：
 *
 * 成年之后一回合推两三年（`routine:adult` 两年、`routine:prime` 三年），
 * 月份几乎不动。拿 `Condition.month` 守时令的话，「年年可能有」实际成了
 * **按世翻的开关**——踏进成年那一刻碰巧是几月，就决定了这一世过不过得上节。
 * 实测四十世里只有十一世到过腊月正月。年节那一卷正是这么写的，
 * 于是一卷本该年年有的内容，四分之三的人一辈子读不到。
 *
 * 所以这一册的卷一律在 `onEnter` 里自己把日历推过去：
 *
 *     onEnter: [{ type: 'time', untilMonth: 8 }, { type: 'time', days: 1 }]
 *
 * `untilMonth` 是**目标**不是增量（`stores/world.ts` 的 `TimeDelta`）：
 * 当月就是 0，否则往前走到下一次。**两条的顺序有意义**——先到那个月，
 * 再推过节本身花掉的日子；反过来写在月底那几天会分道。
 * 条件层只管「有没有这个人、他在不在跟前」。
 *
 * ## 中秋说的是不在一处的人
 *
 * 跟年节分工：年节是**回去**（`kindred:newyear` 走一趟老屋，看见那一年里
 * 变了什么——侄儿长了几岁、婆媳那顿饭有没有人说话）。中秋不回去，
 * 它说的是**今晚不在跟前的那些人**。所以它问的是 `bond.near`，
 * 而不是谁还活着：一个在镇上做工的哥，活得好好的，只是今晚不在。
 *
 * ## ⚠️ 「缺席」是分支，不是前提——头一版写反了
 *
 * 头一版把「有一个不在跟前的哥」写进了事件的 `requires`。**实测 300 世
 * 只有 3.3% 演到**——哥多半就在隔壁村，真离家的只有他去镇上做木匠那一路。
 *
 * 那正是这次改造要治的病，只是换了个原因：从前是「碰巧不在那个月」，
 * 那一版是「碰巧没有人不在跟前」。**一卷四分之三的人读不到的节令，
 * 不管卡在哪一层都是同一个毛病。**
 *
 * 所以前提只剩年纪：**中秋年年有，谁都过**。谁不在跟前是那一卷进门之后
 * 才问的事，问完落到哪一支就说哪一支的话；一个人也不缺的那一年
 * 也有它自己的一句——**人齐不是「没内容」，是另一种内容**。
 *
 * ## 这一册里已经有的两卷，各占一头
 *
 *     中秋　　不在一处的人　　孩子、哥、爹娘今晚谁不在跟前（`bond.near`）
 *     除夕　　一年到头的账　　欠着的、被欠的、清着的（`people.ious`）
 *
 * **每一卷得先说清自己说的是什么。** 六卷都写成「过节了，一家人聚在一起」
 * 等于同一卷演了六遍——两卷都在年下、都是团圆节，要是不各占一头，
 * 玩家读到的就是同一段话换了个月份。
 *
 * 往后四个：上元、端午、中元、祭灶。中元是死了的人，端午是身上的病，
 * 剩下两个还没想好说什么——**想好之前不写**，宁可只有两卷。
 *
 * ## ⚠️ 节日 ≠ 放假，这两件事别并成一格
 *
 * 明代同一天可以同时是：民间岁时节日、朝廷礼仪节日、官员正式节假、
 * 特定身份的休假（宗室／国子监生／庶吉士）、圣节、临时赐假停朝——
 * **六种东西，六个不同的读者**（`design/ming-society.md` 第十二节，
 * 用户 2026-09-09 转引《万历大明会典》卷八十等一手史料）。
 *
 * 最常见的错误是把今天的传统节日整体当成「明代法定节假日」。
 * **《大明会典》「节假」条明确写着百官长假只有三项**：正旦五日、
 * 冬至三日、元宵十日（永乐七年定）。**端午、中秋、重阳都不在里头**
 * ——它们当然是重要节日、有宫廷宴饮，但「有端午宴」推不出「全国官员放假」。
 *
 * 这一册现有三卷（中秋、除夕，加老屋那册的正月里）**全是民间岁时，
 * 一卷也没有声称放假**，所以这条区分眼下还没被违反。
 * **写下一卷时它才第一次真正管事**：
 *
 *     写上元／冬至　  第一层：十天官假、弛夜禁、军民张灯。
 *                    一个农户感觉得到的是**市面和夜禁**，不是「他放假了」
 *     写别的　　　　  第二层：只有节俗，没有假
 *
 * 而**假期那一整轴目前一个读者也没有**：这世界的玩家绝大多数是农户、猎户、
 * 匠户、商户，没有官假可放。按「先有使用者再抽象」，那张「身份对假期」的表
 * 现在不建成数据——等第一卷「当官的那年冬至」或「宗室子弟的读书假」写出来再说。
 *
 * ## ⚠️ 节令制度本身会变，本项目参照嘉靖—万历
 *
 * 嘉靖十四年后，四月八日佛诞的宫廷赐宴改成了四月五日荐麦。
 * **不能把洪武朝的制度原样搬过来**——写任何一卷之前先问它在参照时段什么样。
 *
 * ## ⚠️ 加一卷的代价是可以量的，量完再定 `chance`
 *
 * 每一卷都在成年段抢回合，而**代价累加**：中秋一卷实测让要熬年数的链条
 * 推后约四分之一（同种子对照，见底下 `festival-midautumn` 那一段）。
 * 所以第二卷的 `chance` 定得比第一卷低（0.15 对 0.2），
 * **按量出来的代价定，不按「它有多重要」定**——挤占量得到，重要性量不到。
 */

