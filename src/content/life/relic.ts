/**
 * 那把镰刀。
 *
 * ## 这一卷证的是「遗物不是一次性掉落」
 *
 * 遗物那一环的头一半已经落了：当家的人没了，他用过的那几样留下来
 * （`settleHeads` 里那一段 + `content/relics.ts`）。**而落下之后它什么也不做**
 * ——躺在行囊里，玩家看得见，此外再无下文。
 *
 * 一件永远躺着、从不被消费的东西，跟一个数据结构上的标签没有分别。
 *
 * 所以这一卷要的不是「多年以后再提一次」。**再提一次只是把同一条事实
 * 延迟消费一遍**，它证明不了任何新东西。这一卷要的是：
 *
 * > **人死了，物还在，而你已经快记不清他的样子了。**
 *
 * ## 四条硬约束，缺一条这一卷就不成立
 *
 * ```
 * 一  它得【还在】        问 keepsake 而不是问历史上有过
 * 二  它得带着【来历】    同 id 而没有 keepsake 的（别处捡的）不算
 * 三  隔了【足够多年】    不是同一句话换个地方再说
 * 四  说的是【那个人】    称呼现算，不写死「爹」
 * ```
 *
 * 前三条由 `{ keepsake: { item, years } }` 那一格钉住——它是为这一卷加的
 * 第 38 种条件，而它跟 `{ item: … }` 的分别正是第二条：
 * **光有那件东西不够，它得是他留下的那一件。**
 *
 * ## 门槛二十年，那个数是量出来的
 *
 * 300 世随便过日子，拿到遗物的 176 世：
 *
 * ```
 * 拿到那年他多大    中位 29 岁（最小 5，最大 56）
 * 东西跟了他多少年  中位 34 年（最长 68）
 * 走到最后还在的    176/176 世
 *
 * ≥ 5 年 174 世 · ≥10 年 167 · 【≥20 年 147】 · ≥30 年 108 · ≥40 年 64
 * ```
 *
 * 二十年那一档还剩 147 世够得着，三十年剩 108，四十年只剩 64。
 * **画在四十年就是把这一卷写在分布的尾巴上**——那是这个库反复栽过的地方。
 *
 * ⚠️ 而窗口开 `35–70` 不是拍的：拿到那年中位 29 岁，加二十年是 49；
 * 最早的（5 岁拿到）二十年后才 25 岁。**开口取下界，收口取天年**。
 *
 * ## ⚠️ 这一卷什么状态也不落，而那是有意的
 *
 * 它不改行囊、不加属性、不立旗。因为这一环眼下要证明的是
 * **「那件东西穿过了时间」**，而那件事在它被读到的那一刻就已经成立了
 * ——世界事实是「他二十年前留下它、你现在还带着」，
 * 这一卷只是让玩家看见它。
 *
 * 再落一笔东西反而会稀释它：**遗物的分量来自它不变**。
 */
