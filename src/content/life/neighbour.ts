/**
 * 隔壁。
 *
 * ## 这一册的由来：邻居在这个游戏里从来没有过自己的事
 *
 * 动笔前的调查在 `design/subject-facts.md`。全库四十四册里邻居出现过六次，
 * **六次都是同一个形状**：
 *
 * ```
 * 他来到你家门口 → 说了句话 → 你的日子变了一点 → 他退场
 * ```
 *
 * 他是背景、是岔口、是送信的人，**从来不是那个「发生了什么」的人**。
 *
 * ## 判定标准：不是「玩家能不能看见」
 *
 * 动笔前我提过一个疑问：这个库的每一行正文都是玩家看见的，
 * 没有一处是「镜头切到别人家」——那么「邻居成为主体」会不会天然
 * 只能表现为「玩家看见他家变了」？
 *
 * **那个疑问是错的。** 真正的判定标准是：
 *
 * > 邻居是否存在**独立于玩家行为**的世界状态变化，
 * > 并产生属于邻居自身的后果；玩家看到的只是这些事实的**可观察投影**。
 *
 * 纯玩家视角不是障碍。要审的是「Y 是不是 X 的可观察证据，
 * 而不是 Y 本身冒充了 X」。
 *
 * ## 为什么是添丁，不是「方怀山病了一场」
 *
 * 头一个方案是让东邻的男人病一场、从此种不动地。**候选成立，没能立案**：
 *
 * ```
 * 一、病 → health 下降 的事实依据/生产机制不明（跟生育风险卡在同一处）
 * 二、生活结构高度复用 B 链：年老 → doing 变 → 家人接手
 *     而那一版写的是：病了 → doing 变 → 家人接手
 * ```
 *
 * 第二条是「拿现有系统套一下」。换成添丁绕开了它——
 * **`members` 是 `House` 六格里唯一会动的那一格，而 B 链动的是
 * `doing` 和 `health`，两边不搭界。**
 *
 * ## 这不是新机制，是头一次把已有的机制用在亲属之外
 *
 * 动笔前一手核过三条：
 *
 * ```
 * 一、members 是真实人口集合，不是家庭关系的辅助字段
 *     houseOf() 遍历所有户找人 · 邻居判定读它 · 东西邻的方位直接读
 *     houses['east'].members · 条件层读 · 正文插值读
 *
 * 二、新增成员【自动】进入生命周期——因为 live() 不问户口
 *     for (const [id, person] of Object.entries(roster.value))
 *     enroll 进去就每年长一岁、掷天年 span、按 frailty 可能病殁
 *
 * 三、生产者的适用域是任意 household，而且【已经用过两次】
 *     全库 `age: 0` 只有四处，其中两处落 house: 'old-home'
 *     （`kindred.ts` 的侄儿、侄孙）——那不是玩家的户
 * ```
 *
 * 尤其 `kindred:grandnephew` 那一节跟这一卷**结构完全一样**：
 * 不是玩家家的事、玩家通过认知得知、落在那一户的 `members` 上、
 * 玩家家什么也没变。
 *
 * **所以邻居缺的不是机制。机制在，而且被用过两次。
 * 缺的是有人把它用在亲属之外。**
 *
 * ## ⚠️ 而这一卷逼出了一个真缺口
 *
 * `who` 不写 `surname` 是「跟本家同姓」，那一问从前不带户
 * （`houseSurname(people)`，答的是玩家爹的姓）。`old-home` 跟玩家同姓
 * 是结构保证的，所以两次都没露。**东邻是头一户姓不一样的**——
 * 实测 1385 世里一世也没跟玩家撞姓。不修的话，落进方家的孩子
 * 住在人家院里、报的是你家的姓。已加 `houseSurname(people, houseId)`。
 *
 * ## 可达率（一手量的，3000 世）
 *
 * ```
 * 没有东邻的世界        27.2%   宫、王府、寺、没有居所的一户也没有
 *                               ——那是 birth.ts 写着的设计结论，不是缺口
 * 有女主人              80%     立基那一支挂在 Math.random() < 0.8 底下
 * 她开窗那年还在育龄    69.4%   她比玩家大 18–52 岁（中位 35）
 * ────────────────────────────
 * 占全部世界            50.5%
 * ```
 *
 * ⚠️ **窗口只能开在童年**：玩家 8 岁时她 ≤40 的世界占 41.6%，
 * 20 岁时只剩 2.5%。而 5–14 岁也正是他在自家院子里过日子的年纪,
 * 被动撞见最自然。
 *
 * 育龄那条线不是我拍的，取的是库里既有的口径：`bearing-await` 的
 * `window: { from: 18, to: 45 }`，那儿的注释写着「上限四十五不是
 * 『四十五以后生不了』，是这一卷写的是常态」。
 *
 * ## 三件我决定不做的事
 *
 * **一、不落 `chronicle`。** 年表是玩家人生的账。`kindred:grandnephew`
 * 落了「老屋添了第三代」——那说得通，侄孙是他的血亲。
 * 而隔壁添丁进玩家年表，等于说「这是你人生里的一件事」，
 * **那正好否定了这一卷的全部意思**。
 *
 * **二、不给 `members` 另立一个专门的消费点。** 那会破坏这件事最要紧的地方：
 * 我不是为这个事件给引擎加一个「邻居生孩子系统」，
 * 而是发现现有的人口系统本来就没把「玩家家」和「东邻家」区别对待。
 *
 * **三、不让韩清荷来告诉玩家。** 那一写就前功尽弃——
 * 邻居又变回「主动来到你家门口的人」，而那正是这一卷要翻过来的那一页。
 *
 * ## ⚠️ 一处写死的，标在这儿
 *
 * `given: '秀'`、`gender: '女'`——内容层给不出随机，这两个每个世界都一样。
 * 选女孩是因为**这一卷要的是安静**：这个时代「添丁」说的是男孩，
 * 写成儿子，正文会不自觉滑向「巷子里都在道喜」，
 * 又把这件事拽回社会关系里去了。
 *
 * 代价认：一千个世界里东边生的都是同一个女儿。
 * 要改得等内容层能表达「掷一个」——那是另一件事。
 */
