/**
 * 出师。
 *
 * 这一册只做一件事：**让学徒有个尽头。**
 *
 * ## 在这一册之前，学徒是无期的
 *
 * `youth.ts` 的 `craft` 那一节落 `{ type: 'identity', identity: '学徒' }`，
 * 而**全库没有任何一处改掉它**——一个人十六七岁拜师，到六十岁咽气那天，
 * 人物面板上还写着「学徒」。
 *
 * 这跟守孝那件事是同一个 bug，`mourning.ts` 的文件头早把话说透了：
 *
 * > 由它落那一笔 `undertake done`。**少了它，守孝就是无期的**——
 * > 而那不是礼法，是漏写。
 *
 * 学徒也一样。**十年不出师不是苛刻的师门，是没人写收尾那一卷。**
 *
 * ## 供食、年限：记在「过程中状态」里，不新造字段
 *
 * `Undertaking` 只有四格（`id`/`since`/`until`/`who`），**不许长出 `deadline`**
 * ——用户拍板的三条边界之一，`scripts/undertaking.ts` 守着它。
 *
 * 于是这三件事各归各：
 *
 *     学徒期间靠什么活　　`until: null` 的那条 undertaking 本身就是答案：
 *                         **他这几年是「在学徒」这件事里的人**。住师父家、
 *                         吃师父的饭、不拿工钱——那不是一份工，是一段依附，
 *                         所以它是 undertaking，不是 livelihood
 *     几年算满　　　　　　`since` 存着起年，可条件层现在**没有一格去问它过了多久**
 *                         （`mourning.ts` 也卡在这儿）。所以年限靠散事件的窗口
 *                         近似：19–34 岁之间掷到才演
 *     出师之后去哪　　　　`livelihood: '木工'` + 身份从「学徒」变成「匠人」
 *
 * ## 为什么不做成雇佣
 *
 * 学徒不是打工。他住在师父家、吃师父的饭、不拿工钱——**这是人身依附，
 * 不是劳务合同**。做成雇佣就要有工钱、有工时、有解雇，那四样东西这个世界
 * 一个也没有，造出来只会多一套没人读的格子。
 *
 * 所以这一册全部的机制只有两笔：`undertake done` 和身份换一个词。
 * 剩下的都是话。
 *
 * ## 师傅没了那一种：删过一次，又加了回来
 *
 * 头一版写了两支：师傅还在（把家什给你）、师傅没了（没有人给你出师）。
 * **900 世实跑后一支 0 次，于是删掉了。那是个错误。**
 *
 * 删的时候诊断过两轮，第一轮就错：我 grep 完 `craft-master` 发现除了创建它
 * 那一处全库再没人提，就断定「NPC 只在内容显式写 `alive: false` 时才死」。
 * 查 `people.live()` 才发现有——45 岁往上每年 `(age-45)*0.004`，死因记「老病」。
 *
 * 第二轮诊断对了：**是时序**。师傅拜师时 36 岁，出师窗口 19–34 岁（玩家），
 * 那会儿他 40–55 岁，正卡在死亡概率刚起步的地方。实测 900 世里有师傅的 43 世，
 * **最后全都殁了，可出师那一刻殁的是 0 个**。
 *
 * **可我据此删掉了那条分支，而 `0/900` 只说明「罕见」，不说明「不可能」。**
 * `present` 那支门禁换一批世界就撞上了（主种子 `ujiw3x1bshrk`）：
 *
 *     〔正文〕craft-master（玩家叫他「师傅」）：师傅把那套家什拿出来……推到你面前。
 *
 * 人已经殁了，正文照旧写他把家什推过来。
 *
 * **教训**：真世跑答的是「这个局面常不常见」，不是「它可不可能出现」。
 * 一条极少走到的路仍然要有人写——**它极少演，但它得在**。
 * 对照着看更清楚：`chapters.ts` 里「门下 1200 世零次」查完是**设计**
 * （灵根门槛），写进注释留着；这一条查完是**漏洞**，得补回来。
 * **同样是零次，处置相反，而分辨靠的是查不是数。**
 */
