import type { LifeEvent, SceneLibrary } from '@/types/game'

/**
 * 出师。
 *
 * 这一册只做一件事：**让学徒有个尽头。**
 *
 * ## 在这一册之前，学徒是无期的
 *
 * `youth.ts` 的 `craft` 那一节落 `{ type: 'identity', identity: '学徒' }`，
 * 而**全库没有任何一处改掉它**——一个人十六七岁拜师，到六十岁咽气那天，
 * 人物面板上还写着「学徒」。
 *
 * 这跟守孝那件事是同一个 bug，`mourning.ts` 的文件头早把话说透了：
 *
 * > 由它落那一笔 `undertake done`。**少了它，守孝就是无期的**——
 * > 而那不是礼法，是漏写。
 *
 * 学徒也一样。**十年不出师不是苛刻的师门，是没人写收尾那一卷。**
 *
 * ## 供食、年限：记在「过程中状态」里，不新造字段
 *
 * `Undertaking` 只有四格（`id`/`since`/`until`/`who`），**不许长出 `deadline`**
 * ——用户拍板的三条边界之一，`scripts/undertaking.ts` 守着它。
 *
 * 于是这三件事各归各：
 *
 *     学徒期间靠什么活　　`until: null` 的那条 undertaking 本身就是答案：
 *                         **他这几年是「在学徒」这件事里的人**。住师父家、
 *                         吃师父的饭、不拿工钱——那不是一份工，是一段依附，
 *                         所以它是 undertaking，不是 livelihood
 *     几年算满　　　　　　`since` 存着起年，可条件层现在**没有一格去问它过了多久**
 *                         （`mourning.ts` 也卡在这儿）。所以年限靠散事件的窗口
 *                         近似：19–34 岁之间掷到才演
 *     出师之后去哪　　　　`livelihood: '木工'` + 身份从「学徒」变成「匠人」
 *
 * ## 为什么不做成雇佣
 *
 * 学徒不是打工。他住在师父家、吃师父的饭、不拿工钱——**这是人身依附，
 * 不是劳务合同**。做成雇佣就要有工钱、有工时、有解雇，那四样东西这个世界
 * 一个也没有，造出来只会多一套没人读的格子。
 *
 * 所以这一册全部的机制只有两笔：`undertake done` 和身份换一个词。
 * 剩下的都是话。
 *
 * ## 师傅没了那一种，这一版没有写——理由不是「他不会死」
 *
 * 头一版我写了两支：师傅还在（把家什给你）、师傅没了（没有人给你出师）。
 * **900 世实跑，后一支 0 次。**
 *
 * 头一个诊断是错的，记在这儿免得后人重蹈：我 grep 完 `craft-master`
 * 发现除了创建它那一处全库再没人提它，就断定「NPC 只在内容显式写
 * `alive: false` 时才死，没有自然死亡机制」。**查 `people.live()` 才发现有**——
 * 45 岁往上每年 `(age-45)*0.004` 的概率过不去，死因记「老病」。
 *
 * 真实原因是**时序**，实测：
 *
 *     900 世里有师傅的　　　　　　43
 *       出师那一刻他已经殁了　　　 0
 *       活到世末时他已经殁了　　　43   ← 最后全都死了
 *
 * 师傅拜师时 36 岁，出师窗口 19–34 岁（玩家），那会儿他 40–55 岁，
 * 正卡在死亡概率刚起步的地方。**他确实会死，但死在玩家四五十岁之后——
 * 那时候早出师了。** 所以这一卷永远撞不上。
 *
 * 一段永远走不到的正文跟没写一样，**而且比没写更糟：它会让人以为这件事想过了。**
 * 删掉了。要补的话，缺的不是这一卷的分支——**是「师傅老了之后」那一卷**，
 * 而那一卷的窗口在玩家四五十岁，跟出师根本不在同一段人生里。
 */
export const apprenticeScenes: SceneLibrary = {
  'craft:out': {
    id: 'craft:out',
    title: '出师',
    entry: 'open',
    nodes: {
      open: {
        id: 'open',
        onEnter: [
          { type: 'time', months: 4 },
          // 收掉「在学徒」这件事。不写 `who`——底下分话时再问师傅还在不在
          { type: 'undertake', undertaking: 'apprentice', done: true },
          // 身份从「学徒」换成「匠人」。这一笔是这一册存在的全部理由：
          // 少了它，六十岁的人物面板上还写着学徒
          { type: 'identity', identity: '匠人' },
          // 手艺成了他的营生。从前只有 `has-craft` 这个旗标，
          // 而旗标说的是「他学过」，营生说的是「他靠这个吃饭」——两件事
          { type: 'household', livelihood: '木工' },
          {
            type: 'aspect',
            key: 'learning',
            self: '你出师了。这门手艺往后是你自己的营生。',
          },
        ],
        /**
         * 这一节只做结算，正文在底下那一支里。
         *
         * 但 `blocks` 是必填的（`SceneNode` 要求），所以给一句过渡——
         * **而这句过渡本身有用**：出师不是某一天忽然宣布的，
         * 是活计一件件做下来、有一天忽然够得着了。
         */
        blocks: [{ kind: 'narration', text: '这几年的活，你已经做得跟师傅差不太多了。' }],
        /*
         * 这儿本该有一支「师傅没了」的分岔，删掉的理由写在文件头：
         * **实跑 900 世走不到**——不是他不会死（`people.live()` 里有自然死亡），
         * 是出师窗口那会儿他才 40–55 岁，死在玩家四五十岁之后，那时早出师了。
         */
        next: 'given',
      },

      /**
       * 有人给你出师。
       *
       * 那句「往后是自己的活计了」是这一节的重心——**出师是别人说的话**，
       * 不是自己觉得学成了。
       */
      given: {
        id: 'given',
        onEnter: [{ type: 'chronicle', text: '你出师了，师傅把家什给了你。', tone: 'deep' }],
        blocks: [
          { kind: 'narration', text: '师傅把那套家什拿出来，一件一件擦干净，推到你面前。' },
          { kind: 'narration', text: '「往后是自己的活计了。」他说。' },
          { kind: 'event', text: '你出师了。' },
          {
            kind: 'narration',
            text: '铺子还是他的铺子，可你从这天起，做的每一件活都记在自己名下。',
            tone: 'faint',
          },
        ],
      },
    },
  },
}

