/**
 * 隔了一辈的那个孩子。
 *
 * ## 32.md 整篇写的是一个这个世界里不存在的人
 *
 * 那份文档从头到尾建立在一个前提上：**你活了几百年**。
 *
 * > 你活了六百年。第六百年回到故乡。
 * > 你和当年真正相处过的父母、兄弟、妻子、朋友、师父、孩子，早就死了。
 *
 * 而实测 600 世：**终年 p50=62、max=83，活过九十的零个**
 * （`engine/lifespan.ts` 掷 52–82，身子骨上下挪十年；
 * 全库只有一处 `lifespan` 效果，还是**减**两年的）。
 * 修行不延寿——`flicker` 那一节给的是一点热和一条认知，不是寿数。
 *
 * **所以「几百年后回故乡」在这个库里没有一个人做得到。**
 * 照文档写就是给不存在的人写内容，那是这个项目今天反复戒着的事。
 *
 * ## 但它的核心断言现在就成立，而且已经有人可写
 *
 * 那份文档的第一句加粗是：
 *
 * > **血缘存在 ≠ 社会关系存在 ≠ 情感关系存在。**
 *
 * 这句话不需要六百年。**它需要的只是「隔了足够多的辈分」**，
 * 而这个库里已经有那个人了：`kindred.ts` 立的侄孙——
 * 哥的儿子的儿子，跟玩家隔着两辈。
 *
 * 实测（900 世）：
 *
 *     侄孙出生                     32 世（3.6%）
 *     他活到十岁而玩家还在         31 世   ← 这一卷的分母
 *     他出生那年玩家多大           p50 = 48
 *     他十岁那年玩家多大           p50 = 58
 *
 * **一个五十八岁的人，和一个十岁的、姓同一个姓的孩子。**
 * 血缘是实的（关系图上真有那条边），而共同经历是零。
 * 32.md 说的那件事，在这个尺度上是同一件事——
 * 只是差的不是六百年，是两辈人。
 *
 * ## 这一卷不做的三件
 *
 * 文档后半列了一整套「长生者面对后人」的选择（赠财富、传功法、
 * 提供庇护、带进宗门、什么都不做），每一条都有代价。
 * **那些一件也不做**，理由是同一个：**它们全要长生**。
 *
 * 等哪天真有人活过两百岁——那需要修行线一路走通到延寿，
 * 而今天 `flicker` 才 0.1%——再回来写。到那时这一卷是它的雏形，
 * 不是它的替代品。
 */
