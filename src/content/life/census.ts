/**
 * 造册那年，册子上那一行跟你家对不上。
 *
 * ## 这一册验的是一件别的事
 *
 * 不是「老友帮忙」，是**过去认识的人，三十年后仍然是一个有现实作用的人**。
 *
 * 库里到今天为止，人际关系是一种**状态**：他在不在、活着没有、
 * 好感多少。而这一卷要证的是关系可以是**一种别人替代不了的能力**——
 * 这件事只有一个从小在这条巷子里长大的人办得了，
 * 不是因为他跟你好，是因为**他见过**。
 *
 * ## 制度不是我编的，是这个世界已经写好的
 *
 * `design/ming-society.md` 第五节两条硬依据：
 *
 * > 里甲：110 户为一里……**邻居首先是同一里甲的人**，互相有连带责任。
 *
 * > 《大明律》多处以「邻佑」「四邻」为见证或连坐对象。
 * > → 邻居是**法律关系**：他见过你家的事，可以作证，也可以告发。
 *
 * 还有一条决定了这一卷的形状——洪武三十一年《教民榜文》：
 *
 * > 「民间户婚、田土、斗殴、相争一切小事，**不许辄便告官**，
 * > 务要经由本里老人、里甲断决」
 *
 * 所以「找一个从小看着你长大的人出面说话」**不是人情，是这个制度
 * 本身要求的形式**。册上的数不对，凭据不是文书，是人。
 *
 * ## 里长这个人已经在库里了
 *
 * `mountain:census`（药庐那一卷）定过他的样子：秋后造册，挨着门问，
 * 站在门口不进来，问几口、姓什么、多大年纪，写完就走。
 * 这一卷用同一把尺子——**他不是来找麻烦的，他是来抄数的**。
 *
 * ## 三条约束（跟 GPT 过完之后定的）
 *
 * 一、**里长先来，玩家自己想起那个人。** 那件麻烦是世界给的，
 *     不是玩家挑的；而「想起他」这一步由玩家做，不由系统弹一个
 *     「要不要找老友帮忙」的选项。
 * 二、**留不去找他的路，而且那条路不是错的。** 自己去跑也办得成，
 *     只是另一种办法、另一种代价。**多数事没有后果，
 *     正是这个世界真实的地方**。
 * 三、**办完即止。** 不解释他为什么肯，不发奖励，不写关系总结，
 *     不替玩家回忆三十年前那句「有事言语一声」——
 *     那句话写在 `playmate.ts` 的第三卷里，玩家自己会想起来。
 *
 * ## 他作证的只是他亲眼见过的那一部分
 *
 * ⚠️ **这一条是这一卷的分寸所在。** 他能说的是
 * 「这是我从小一块长大的，他家原先就在巷子东头」——
 * 而**不是**「所以这块地该记在他名下」。
 *
 * 人提供事实，册子登记，官役核验。
 * 把他写成一个万能的「证明人」，这个世界的官府就垮了。
 *
 * ## 入场不问「认识多少年」
 *
 * 条件是三条：他还在、此前走得近（`said-come-to-me` 那面旗）、
 * 眼下真有这件事。**一格也不问年数。**
 *
 * 那一册三卷的窗口是 8–14 / 18–30 / 35–70，走到第三卷
 * 「还走动」那一支的人，跟他认识本来就三四十年了——
 * **三十年是它读起来特别的原因，不是它成立的条件**。
 * 按年数判会造出一个「三十年老友系统」，而那正是要避开的东西。
 */
