/**
 * 儿子长大了。
 *
 * ## 这一册的由来：一个被问了 665 次、一次也没成立的条件
 *
 * 全库扫条件时挖到的：`festival:midautumn` 那一支 `CHILD_AWAY`
 * （「孩子今年没回来」）**被问 665 次零成立**，而一手核验发现
 * 全库提到玩家儿子的只有 `bearing.ts` 三处——**全在出生那一刻**。
 *
 * 出生之后整个世界对他是空白，而已经有三处内容在等他长大：
 *
 * ```
 * routine:prime seen  「孩子长得比你想的快。有时候你看他做事的样子…」
 * festival:midautumn  「孩子今年没回来」          ← 665 次零成立
 * ```
 *
 * 口径立在 `design/son-grows-up.md`（跟 GPT 过完之后定的）。
 *
 * ## 一句话：他从「你的孩子」变成「一个人」
 *
 * 父亲的意见很重要，**但不是世界规则**。这一册不做成
 * 「儿子想去哪 → 玩家允许／拒绝 → 产生收益」——那会把他做成
 * 玩家的第二个角色面板，而这个库一直在避开那种东西
 * （`leanings.ts` 的立意：念头从人生里长出来，不是另一套剧本）。
 *
 * **最值得写出来的两种情形恰恰是**：
 *
 * ```
 * 你不同意，他还是去了。
 * 你催他出去，他反而不想走。
 * ```
 *
 * ## 这一卷只做一件事：让世界注意到他是个人
 *
 * 不分路、不做决定、不落任何「他要走了」的旗。
 * 十六岁那年他身上有一件具体的事被你看见——**看见的是什么，
 * 由他的性情定**（引擎在他出生那一刻就随机给了，六种都出得来：
 * 实测精明 10 / 温和 7 / 暴躁 7 / 木讷 7 / 刚硬 6 / 谨慎 3，n=40）。
 *
 * 而**你什么也做不了**。这一节没有选项——这是有意的：
 * 「他长大了」不是一件需要你处理的事，是一件正在发生的事。
 *
 * ## ⚠️ 这一卷是【认知节点】，不是无效节点
 *
 * 它不落旗、不进编年、不给好感——**而那不等于它没有作用**。
 * 它承担的功能跟别的卷不同：
 *
 * ```
 * son:grown  = 玩家第一次【重新认识】这个人
 *            ≠ 玩家第一次【处理】一个事件
 * ```
 *
 * 人物变化首先改变玩家的理解，不一定立即改变世界状态
 * ——这跟 `leanings` 那一族的方向是一路的。
 *
 * **所以别为了「证明它有用」给它加奖励、好感、性情旗或编年记录。**
 * 那会把一次细腻的观察重新游戏化。
 *
 * 哪天真有内容要引用「他记得家里的账」这类事实（比如他接管账目、
 * 质疑你的记法），**那时候再落**——不是现在为了让它有用而落。
 *
 * ## 唯一落下的一格是 `doing`，而它不是奖励
 *
 * 四条分支各落一句 `person.doing`（「跟着家里做活，做法是他自己的」之类）。
 * 这跟上面那条不矛盾：**`doing` 是世界事实，不是给玩家的回报**
 * ——它答的是「这个人此刻在做什么」，人物面板上那一行。
 *
 * 而且 `types/game.ts` 的 `doing` 那一格自己等着这件事：
 *
 * > 一个孩子长到十几岁真的开始做活，该由**内容**把这一格填上
 * > （他下了地、进了铺子、出了远门），不该由一句按年龄现编的话顶着。
 * > **那是这一格唯一诚实的填法，也还没有人写。**
 *
 * 这一卷是那个「还没有人写」的内容。
 *
 * ⚠️ 措辞对所有营生成立（`doing` 存的是定值，用不了 `{chore}`）：
 * 写「跟着家里做活」，不写「下地」——那一年家里过的日子有七种。
 *
 * ## 硬事实（动笔前量的，600 世）
 *
 * ```
 * 有过儿子          88 世（14.7%）
 * 儿子长到 16 岁    83 世（94% 都活到成年）
 * 那一年玩家岁数    中位 37
 * 那一年玩家还活着  83/83 —— 他一定在场
 * 那时家里过的日子  farm 36 · shop 16 · craft 10 · yamen 7 · hunt 7 · clinic 5
 * ```
 *
 * ⚠️ **最后一行是硬约束**：日子分散在七种，所以这一卷的正文
 * **一个字也不能假定他家种地**。`{chore}` 那个记号问的正是
 * 「这家人过的是什么日子」，用它。
 *
 * ## 条件用 `family` 不用 `bond`
 *
 * `bond` 只支持 `kind`/`alive`/`near`/`exists`——**问不了岁数**
 * （`conditions.ts:275-295`，一手读过）。`family` 支持 `age` 和 `temper`。
 */
