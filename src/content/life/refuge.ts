/**
 * 去投奔。
 *
 * ## 这一卷要证明的那一句话
 *
 * 14.md 那一节写着：
 *
 * > 一个逃犯去找兄弟、亲戚、旧友、旧情人、师父、旧东家、同乡、宗族，都有可能。
 * > 但是这些人对他的反应应该不同：收留 / 拒绝 / 害怕 / 敷衍 /
 * > 提供食物但不让过夜 / 私下报官 / 直接抓住邀功 / 因为恩情帮助逃走。
 * > 这比「NPC 好感度 100，所以必定帮助你」真实得多。
 *
 * 所以这一卷刻意把三种结果挂在**同一个人**身上：同一个师傅、同一份情分，
 * 你去找他，可能扑空、可能他自己就在难处、也可能他一句话不问就留下你。
 *
 * **分岔的依据一次也没有读过好感。** 三条 `branches` 读的是：
 * 他还在不在（`family.alive`）、他这几年过得怎么样（`family.health`）、
 * 他多大年纪了（`family.age`）。好感在这一卷里全程不变——
 * 变的是这个人自己的生死、身子骨和岁数。
 *
 * ## 为什么是师傅，不是恩人
 *
 * 14.md 举的例子是「十五岁被救过，二十年后去投奔恩人」，而山道上那个猎户
 * 今天刚进人口册（`engine/wounded.ts` 的 `acquaints`）。可实测他 500 世里
 * 只出现 6 次（1.2%），再叠上「家底跌破线」是千分之一量级——
 * **那是在没有样本的地方造读者。**
 *
 * 拜过师的实测 5.8%，其中成年后家底跌破 22 的占 4.3%（17/400 世）。
 * 这一卷写在师傅身上，恩人那条等 `road-hunter` 的出场率上来再说。
 *
 * ## 窗口三十开头，是被数据逼的
 *
 * 头一版写二十二，因为入场条件（家底跌破线）在那个岁数就成立了。
 * 而实测 900 世里，**进卷那一刻玩家的年龄 p50=23、p75=23**——
 * 四分之三的人在二十三岁以前就来了，师傅那时才四十出头。
 *
 * 后果是三档塌成一档：扑空和难处各零次，全走收留。
 * 我为此把年纪门槛从 58 挪到 50 再挪到 44——**挪的是尺子，
 * 被量的东西一动没动**。
 *
 * 三十岁这个起点不是迁就判据，是内容本来就该是这样：一个二十二岁、
 * 刚出师没几年的人就跑回去投奔师傅，那太快了，他还没真的试过。
 * 三十岁破了产才是走投无路。改完之后 1500 世实测：
 *
 *     扑空 6 世 · 难处 6 世 · 收留 12 世 · 「算了」26 世
 *
 * ## 窗口尾巴留到六十二
 *
 * 重读一遍 `open` 那一节才想明白：**那一节写的本来就不是投奔的口气。**
 * 你想起的是一条街、一家面摊、一道磨亮的门槛。一个五十五岁、
 * 一辈子没做成的手艺人回那条街，他不是去讨饭的，他是去看看还在不在。
 * 而到了才知道人没了——**那正是扑空那一节最好的读法。**
 *
 * ## 「算了」那一条不是弃权
 *
 * 拉不下这个脸是真实的，而且实测比去还常见（26 比 24）。
 * 所以它是一条正经的路，有自己的一节正文，不是「跳过这个事件」。
 */
