/**
 * 她。
 *
 * ## 这一册的由来：一个天天在场而从未被看见的人
 *
 * 动笔前的调查在 `design/the-wife.md`，三个一手量的数：
 *
 * ```
 * 她的 doing 一辈子变过几种   1 种（800 世里成过亲的 354 世全部）
 * 引擎给了她性情，六种都出     而【零处内容读它】
 * 她一辈子说过六句话           全在同一个晚上（mountain 那卷，分母 0.37%）
 * ```
 *
 * 对照表（全库读性情的处数）：
 *
 * ```
 * 娘 10 · 哥 8 · 儿子 7 · 侄儿 4 · 田主 2 · 嫂子 2 · 配偶 0
 * ```
 *
 * **连隔着一户、一年见几面的嫂子都有两处，而天天在场的她一处也没有。**
 *
 * ## 一句话：「天天在场」被等价成了「没有生命周期」
 *
 * 儿子那一册验的是「一个人**离开**玩家视野之后仍然在生活」。
 * 这一册要验的是更基础的那条：**一个始终在你身边的人，
 * 是不是真的作为一个独立的人在持续变化**。
 *
 * ## 这一卷只验一件事
 *
 * > 一个已有性情的人，在日常生活里，会不会做出一件
 * > **玩家没有教过、而能体现她性情的事**？
 *
 * 跟 `son:grown` 严格对照：
 *
 * ```
 * 儿子   父亲看见儿子做事 → 意识到「他已经有自己的做法」
 * 妻子   丈夫看见妻子做事 → 意识到「她原来有自己的做法」
 * ```
 *
 * **这里不需要婆婆。** 婆媳那一层要等她们之间先有一件具体的事
 *（一手核验：妻子在正文里出现 9 处，跟娘同在一句的 **0 处**——
 * 她们之间眼下没有任何交互事实，而嫂子那条 `tie` 是从
 * 「一顿饭没说话」「添饭时拉着手」「那副镯子」里长出来的。
 * **先有事，再有边，顺序不能反**）。
 *
 * ## ⚠️ 写她做的那件事，然后停住
 *
 * ```
 * ✗ 「有一天你忽然发现，她做事很细心。」        ← 标签展示，不是世界
 * ✗ 「你这才发现她原来是个谨慎的人。」          ← 把玩家该自己形成的认知抢走了
 * ✓ 「天还没亮，她把门闩又推了一遍。
 *     推完了没走，又伸手摸了一下。」            ← 然后停止
 * ```
 *
 * 结构是：**性情 → 现实处境 → 她做了一件具体的事 → 你看见 →
 * 你自己形成判断**。最后一步不由正文替玩家做。
 *
 * ## 措辞对所有营生成立
 *
 * 跟儿子那一册同一条硬约束：家里过的日子有七种，
 * **正文一个字也不能假定她在灶上或田里**。所以写的是
 * 门闩、灯、碗、账、孩子——**每一户人家都有的东西**。
 */
