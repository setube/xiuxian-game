/**
 * 一条史实性内容的参照窗口。
 *
 * ## 这一格要防的是什么
 *
 * > 一个作者看过某个宋代材料，觉得「挺有古味」，两年以后悄悄写进明代事件。
 *
 * 防不住它的原因不是没人在意，是**「查到的」和「推出来的」写下来长得一样**。
 * 两年后回头看，`'爹爹娘娘'` 和 `'父亲母亲'` 都只是两个词，谁也认不出前者
 * 引得出宋人笔记、后者是我们为游戏语言定的。等到要把世界统一到某一朝的礼制上，
 * 分不出哪几条能动、哪几条不能动，只好整层重写。
 *
 * 所以每条史实性内容带三格，**缺一格门禁就报**：
 *
 *     period   这条材料出自哪个时段        '嘉靖—万历' / '宋' / '通用'
 *     source   出处原文，或为什么这么定    '《礼部志稿》卷十六：亲王入朝…'
 *     status   查到的还是推出来的          '史料' / '合理化'
 *
 * ## 三格各自守什么
 *
 * `status` 分的是**证据的性质**：`史料` 引得出出处，`合理化` 是我们为游戏语言定的。
 * 这一格早就在（从前叫 `level`），它管的是「这句话能不能当依据用」。
 *
 * `period` 分的是**证据的年代**，是这次补上的那一格。它跟 `status` 正交——
 * 一条出处极硬的材料完全可能来自另一个朝代，而那恰恰是最危险的一种：
 * **它有出处、经得起追问，只是不是这个世界的朝代。** `status` 拦不住它，
 * 因为它确实是史料；`source` 也拦不住，因为朝代埋在散文里，机器读不出来。
 *
 * `source` 守的是**这句话自己要站得住**——「明代」两个字不算出处，
 * 「《礼部志稿》卷十六：亲王入朝，在朝廷则君臣礼，至便殿则叙家人礼」才算。
 * 合理化那一级同理，得写清楚为什么这么定、它软在哪儿。门禁按字数量这一条。
 *
 * ## 只做两档
 *
 * `status` **只有 `史料` / `合理化` 两档**，后续如有必要再扩。
 * 【用户 2026-09-07 明说：不要提前做复杂】
 *
 * 中间档（「大概是这么叫的」「多半如此」）看着有用，实际是把判断推迟：
 * 一条材料要么引得出出处，要么是我们定的——写不出出处就是 `合理化`，
 * 在 `source` 里说清楚为什么这么定即可。给它一个中间档，只会让所有
 * 拿不准的都堆进去，那一格于是什么也不再区分。
 */

/**
 * 世界的参照时段。
 *
 * `design/ming-society.md` 定的：明 276 年不是一个模板，洪武朝的里甲严密、
 * 户籍不动、实物赋役，跟万历朝的白银流通、市镇勃兴、户籍松弛是两个社会，
 * **混用它们世界就会自相矛盾**（一边「不许离乡」，一边「出门做工」）。
 *
 * 注意这是**参照，不是时间轴**：王朝架空，不锁在嘉靖某一年，也不用真实年号
 * 纪年（年号另有一套，见 `content/eras.ts`）。这个常量的用处只有一个——
 * 让门禁认得出「这条材料不是这一段的」。
 */
export const REFERENCE_PERIOD = '嘉靖—万历'

/**
 * 不属于任何一朝的材料。
 *
 * 「父亲」「母亲」「兄长」这类通用书面语在历代文献里既是称呼也是叙述用词，
 * 给它标一个朝代反而是假精确。这一档**不触发时代错位**。
 */
export const TIMELESS = '通用'

/** 查到的（引得出出处），还是推出来的（我们为游戏语言定的） */
export type AttestStatus = '史料' | '合理化'

export interface Attestation {
  /**
   * 这条材料出自哪个时段。
   *
   * 是这个世界的参照段就写 `REFERENCE_PERIOD`；不属于任何一朝的写 `TIMELESS`；
   * **出自别的朝代就照实写那个朝代**（`'宋'`、`'唐'`），不要为了让门禁闭嘴而改成
   * 参照段——门禁报出来的正是需要人看一眼的那些格。
   */
  period: string
  /** 史料写书名卷次；合理化写为什么这么定，以及它软在哪儿 */
  source: string
  /** 查到的 vs 推出来的。只有两档 */
  status: AttestStatus
}

/**
 * 一条出处至少要写这么多字。
 *
 * 这个数不是量出来的，是定的——它守的是一条纪律：**「明代」两个字不算出处。**
 * 一句话说不清一个词是从哪儿来的，这一层就退回成「作者的临时感觉」，
 * 而分两档的全部意义正是不让它退回去。
 */
export const MIN_SOURCE_LENGTH = 20

/**
 * 这一格是不是时代错位——**有出处，但不是这个世界的朝代**。
 *
 * 只对 `史料` 成立：`合理化` 那一级本来就不声称属于哪一朝，
 * 它的 `period` 写什么都不构成「拿别朝的东西冒充本朝」。
 */
export function isOutOfPeriod(attested: Attestation): boolean {
  if (attested.status !== '史料') return false
  return attested.period !== REFERENCE_PERIOD && attested.period !== TIMELESS
}
