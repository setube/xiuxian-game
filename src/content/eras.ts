/**
 * 年号词库。
 *
 * ## 为什么是一张人工筛过的表，不是两个字随机拼
 *
 * 年号的构词习惯很窄：承、景、永、隆、嘉、德、弘、正、泰、成、宣、康、和、宁、
 * 安、庆、绍、启、顺——这些字两两一拼，多数都像。可「像」不是「是」：
 * 随机拼出来的会有「永恒」「无敌」「天帝」这种一眼就是游戏里的词，
 * 也会有「永乐」「万历」这种一眼就是明朝的词。前者破坏质感，后者把架空王朝
 * 读成换皮明朝。**两头都得靠人挑，机器挑不出来。**
 *
 * 每一个词标一个 `style`。眼下没有内容读它——它在这儿是给挑词的人看的：
 * 一个王朝十几个年号，不该全是「祈年」那一路。
 *
 * ## 这些词几乎都在某个朝代或日本用过
 *
 * 两千年里能用的好字就那么几十个，任何顺耳的组合都难保没人用过：
 * 「景和」是南朝宋前废帝的，「承和」「正和」是日本的，「泰和」是金章宗的。
 * **排除的只有两类**：明代（含南明）的全部年号，和几个家喻户晓到一读就出戏的
 * （「永和九年」那种）。别的撞了就撞了——史上本来也常撞。
 *
 * 参照时段是嘉靖—万历（见 `design/ming-society.md`），所以审美偏明代：
 * 平和、祈年的多，「贞观」「开元」那种气象大的少。
 */

export type EraStyle = '平和' | '祈年' | '中兴' | '肃穆'

export interface EraName {
  /** 两个字 */
  text: string
  /** 这个年号是什么气质。给挑词的人看的，眼下没有内容读它 */
  style: EraStyle
}

