/**
 * 一处地方。
 *
 * 玩家攒线索攒的就是这个：**两条不相干的消息指向同一处**，
 * 那件事本身就是一种验证——而那是他唯一能用的工具。
 */
export interface Place {
  id: string
  /** 玩家会怎么称呼它 */
  calls: string
  /** 那儿真的有东西吗 */
  real: boolean
  /** 跑一趟要多久 */
  days: number
  /**
   * 跑到了才发现那儿其实是什么。
   *
   * 缺省那几句（「就是个寻常地方」「围着转了两圈，什么也没有」）
   * 说的是**那儿真的什么也没有**。可有些地方不是空的，
   * 是**有东西，但不是他找的那个**——南山里那个会拳脚的道士就是。
   *
   * 这两种落空在玩家心里的分量完全不同：前一种他知道自己被骗了，
   * 后一种他见着了一个真人、说了话、住了两天，
   * **然后带着「原来不过如此」回家**。而那句「不过如此」是错的。
   */
  instead?: readonly string[]
  /**
   * 这一趟在日录里沾上什么。
   *
   * 多年以后那一句要靠它把这一天翻回来——
   * `hindsight.ts` 认的是 tag，认不了地名。
   */
  tag?: string
}

