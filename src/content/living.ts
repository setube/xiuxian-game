/**
 * 出身 → 日子。
 *
 * `Record<OriginId, Living>` 是有意的：**加一种出身，这里不表态就编译不过。**
 * 能用类型守住的就别拿门禁去守。
 *
 * 键从前是那个混装的行当名，现在是出身主键。这里**故意不改成按业或按产查**：
 * 「过什么日子」是那一整家的样子决定的，不是某一格决定的——
 * 护送那一家的业是护送，可孩子看见的是院里的兵器架和墙上的路图，
 * 那更接近手艺人家的日子（`CRAFT`），不是「护送」这个词能推出来的。
 */
export const LIVINGS: Record<OriginId, Living> = {
  farm: HOMESTEAD,
  hunt: HUNT,
  craft: CRAFT,
  cloth: SHOP,
  inn: SHOP,
  tavern: SHOP,
  herb: CLINIC,
  escort: CRAFT,
  office: OFFICE,
  yamen: YAMEN,
  manor: MANOR,
  court: PALACE,
}

/**
 * 抚养人的营生 → 日子。
 *
 * 键取的是 `circumstances.ts` 里 `Kin.doing` 那几个字，一字不差。
 * 对不上就返回 undefined，于是自动落回这个家——
 * 姐姐、兄长、叔父把你拉扯大都走这一条，**而那是对的**：
 * 家还是那个家，只是当家的人换了。
 */
/*
 * 这里从前有一张 `KEEPER_LIVINGS`：拿抚养人的**营生**当键，
 * 查他过的是什么日子（`讨饭的 → BEGGING`、`逃难路上的人 → ADRIFT`）。
 *
 * 那张表让 `Person.doing` 一格说了两件事——面板上给人读的一句话，
 * 和一个判定用的键。它的注释里写着「这里改一个字，那边就查不到，
 * 静默落回这个家」，而**没有任何机器看着那句警告**。
 *
 * 后来真踩中了：「逃难路上的人」是一句会过期的话（逃难会结束），
 * 为了不让它二十年后还挂在面板上而删掉，`adrift` 那种日子就跟着没了。
 *
 * 现在「他过什么日子」有自己的一格（`Person.living`），
 * 存的是这份内容里的 id，由 `livingById` 换回来。
 */

/** 这一行出身对应哪一种日子 */
export function livingOfOrigin(id: OriginId): Living {
  return LIVINGS[id]
}

/**
 * 按 id 找一种日子。
 *
 * 只有一个使用者：`character.ts` 里那个解析链的顶端。存下来的是一个 id
 * 字符串（要进存档），取用时得换回这份内容里的那一格。
 *
 * 找不到就返回 undefined，调用处落回下一级——**而这是一次静默降级**，
 * 所以拼错的 id 不能指望运行期拦住。拦它的有两处：
 * `character.liveAs` 写入时当场喊，`scripts/verify.ts` 在门禁期对全库查。
 */
export function livingById(id: string): Living | undefined {
  return ALL_LIVINGS.find((one) => one.id === id)
}

/** 全部日子，去重。门禁遍历用 */
export const ALL_LIVINGS: readonly Living[] = [
  HOMESTEAD,
  MANOR,
  HUNT,
  CRAFT,
  SHOP,
  CLINIC,
  OFFICE,
  YAMEN,
  PALACE,
  BEGGING,
  TEMPLE,
  ADRIFT,
  FALLEN,
  MARKET,
  HIRED,
]
