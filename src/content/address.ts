/**
 * 没有封号的人被怎么称呼。
 *
 * 这是全作第二处非分性别不可的地方，理由跟第一处（宗室封号）同源：
 * **称呼语本身带性别**，「公子」落在女孩身上是穿帮。
 * 别处一律不分——不是因为古代女子的人生和男子一样，
 * 而是因为写一半比不写更糟。
 */
const PLAIN: Readonly<Record<Gender, string>> = { 男: '公子', 女: '姑娘' }

/**
 * 别人当面怎么称呼他。
 *
 * 削爵那一卷里，这一格从「殿下」掉到「公子」——两个字就把
 * 整件事说完了。而同一天他开口叫的还是「娘娘」。
 */
export function titleFor(identity: string, gender: Gender): string {
  return HONORIFICS.find((one) => one.identity === identity)?.word ?? PLAIN[gender]
}

/** 全库一共有几种带封号的敬称。**门禁拿它报覆盖率，别在那边另抄一张** */
export const HONORIFIC_IDENTITIES: readonly string[] = HONORIFICS.map((one) => one.identity)

/**
 * 这一层每一个词各自的依据，三张表拉平成一张。
 *
 * **门禁拿它报「史料几条、合理化几条」**，别在那边另抄一份：
 * 抄一份的话，往表里添一个词而忘了给它写出处，门禁不会吭声。
 */
export const ATTESTATIONS: readonly { where: string; attested: Attestation }[] = [
  ...REGISTERS.map((one) => ({ where: `教养:${one.id}`, attested: one.attested })),
  ...RANK_CALLS.map((one) => ({
    where: `爵位:${one.rank}·${one.bond}·${one.manner}→${one.word}`,
    attested: one.attested,
  })),
  ...HONORIFICS.map((one) => ({
    where: `身份:${one.identity}→${one.word}`,
    attested: one.attested,
  })),
]
