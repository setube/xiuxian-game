/**
 * 这个爵位、这层关系、这个场合，开口叫什么。
 *
 * 返回 `undefined` 表示这一格爵位那张表答不上来——**调用方回落到教养那一层**。
 * 不在这儿兜底，理由跟 `kinCall` 那一处同源：兜了底，
 * 「这个爵位没有专门的叫法」和「它的叫法正好跟寻常人家一样」就分不开了。
 */
export function rankCallFor(rank: string, bond: Bond, manner: Manner): string | undefined {
  return RANK_CALLS.find((one) => one.rank === rank && one.bond === bond && one.manner === manner)
    ?.word
}

/**
 * 有封号的人，别人当面怎么称呼。
 *
 * 「殿下」「世子」跟前两张表的性质完全不同：它们**带着政治身份
 * 和礼仪距离**，不是普通的亲属称谓。所以它们跟着 `identity` 走，
 * 而 `identity` 是一道旨意就能改的东西。
 *
 * 这张表也是全层里史料最硬的一张——「世子」不是谁编的一个尊称，
 * 是《礼部志稿》卷十五里写明的一级宗室身份。
 */
export interface Honorific {
  identity: string
  word: string
  attested: Attestation
}

