import type { Bond, Gender, Trade } from '@/types/game'

/**
 * 称谓语境。
 *
 * ## 「皇子就该满嘴父皇母妃」是个误区
 *
 * 影视剧把宫廷称谓压成了一套固定词汇，可古代称谓高度依赖
 * **朝代、场合、身份关系**，不能把不同朝代的宫廷叫法混在一起用。
 * 宋代皇室内部的日常称呼其实相当家常：皇子称父亲可以是「爹爹」，
 * 称母亲「娘娘」，兄弟之间按排行叫「大哥」「九哥」，
 * 并不普遍使用「父皇」「皇兄」这一套。清代又明显不同——
 * 「阿哥」本是满语里的兄长称呼，清初用于贵族子弟，
 * 后来才成为皇子的专称，而官方文书里另有「皇某子」的制度化写法。
 *
 * 所以这一层要的不是「给皇子发一套特殊词汇」，而是那句更朴素的话：
 * **一个人管家里人叫什么，取决于他是在哪儿学会说话的。**
 *
 * ## 这一层为什么非有不可
 *
 * 在它落地之前，四种出身的孩子管爹一律叫「爹」——`calls` 是
 * `content/circumstances.ts` 那张境况表里写死的一个字符串，
 * 而境况跟户籍是**正交**的：境况只管「关系网长什么样」
 * （有没有爹娘、谁把你养大），管不着这家是种地的还是坐龙椅的。
 *
 * 于是童年那一卷里会读到这么一句（这是实测跑出来的，不是设想）：
 *
 *     后来母妃带你去给爹问安。
 *
 * 「母妃」是硬写在正文里的宫廷词，「爹」是插值出来的寻常人家的词，
 * 并排站在同一句话里。**身份是皇子，台词却像普通农户。**
 *
 * ## 称谓有两个方向，而这两个方向的来源不一样
 *
 * - **他怎么称呼别人**（下面的 `Register`）跟着**教养**走。
 *   话是小时候学会的，学会了就改不掉——削爵迁出京城以后，
 *   他开口还是那一套，因为没有人能在四十天的路上把一个人重新教一遍。
 * - **别人怎么称呼他**（下面的 `titleFor`）跟着**身份**走。
 *   旨意当天下来，第二天街上就没有人再叫他殿下了。
 *
 * 这两件事在削爵那一卷里同时发生，而且**朝相反的方向脱节**。
 * 跟 `identity`（社会身份）和 `living`（实际生活状态）那一次同构：
 * 一格说变就变，另一格纹丝不动，分开之后才写得出那种别扭。
 *
 * ## 只做有使用者的那几维
 *
 * 完整的称谓规则是「关系 × 双方身份 × 正式程度 × 时代礼制 × 当前场合」。
 * 这一版只做前两维，另外两维**现在没有使用者**：
 *
 * - **时代礼制**：这个世界根本没有朝代设定。「本朝」全库出现过两次，
 *   两次都在注释里（`types/game.ts` 和 `youth.ts` 里那句「本朝女子不应举」），
 *   **正文一个字也没提过朝代**：没有国号、没有年号、没有一条礼制条文。
 *   凭空造一张朝代对照表，等于先造阶梯再找楼——而这个项目已经吃过一次那种亏。
 * - **正式程度 / 当前场合**：库里他没有一句在殿上开口的台词。
 *   年表和大事记里那两句「父皇大行」是史笔，本来就该用礼制词，
 *   而它们是硬写的正文，不经过这一层。
 *
 * 等哪天真写出「他跪在殿上开口回话」那一卷，再补场合这一维——
 * 到那时有具体内容逼着，形状才定得准。**先有使用者，再有抽象。**
 */

/**
 * 一个人学会的那一套称呼。
 *
 * `kin` 里没写的关系一律回落到境况表那个 `calls`。这不是省事：
 * **绝大多数关系在哪一套话里都是同一个字**，逐条铺满只会让
 * 「哪几个字真的不一样」淹在一片相同的字里。
 */
export interface Register {
  id: string
  /** 这套话是在什么样的人家学的。走查报表用 */
  learntIn: string
  /** 这套话里，家里各人怎么叫 */
  kin: Partial<Record<Bond, string>>
}

export const REGISTERS: readonly Register[] = [
  {
    id: 'palace',
    learntIn: '宫里',
    /**
     * 宫里那一套。
     *
     * 「爹爹」「娘娘」不是写错了——宋代皇子日常就是这么叫的。
     * 满口「父皇母后」的是戏台上的皇子，不是宫墙里长大的孩子。
     *
     * 兄弟本该按排行叫「大哥」「九哥」，可这一版没有排行这一格数据。
     * 硬编一个数字比不写更糟：「你上头有七个兄姐」那句话里，
     * 谁是老几出生那一刻并没有掷过。留通称，等排行真有了再说。
     */
    kin: { 生父: '爹爹', 生母: '娘娘', 兄: '哥哥', 姐: '姐姐' },
  },
  {
    id: 'study',
    learntIn: '读书人家',
    /**
     * 读书人家那一套。官宦和王府共用。
     *
     * 这一格是这一层不姓「皇室」的证据：**称谓的差别来自语言环境，
     * 不来自爵位高低。** 府衙里那个八品小官家里，孩子开口是
     * 「父亲」「母亲」，因为娘出自书香人家、从小教他认字；
     * 王府世子在家里也是这么叫——他跟父亲之间那声「父王」
     * 是朝堂上的事，不是饭桌上的事。**父子私下和朝堂仪礼，
     * 本来就是两个语言环境。**
     */
    kin: { 生父: '父亲', 生母: '母亲', 兄: '兄长', 姐: '姐姐' },
  },
]

/**
 * 哪种人家教哪一套话。
 *
 * 没列进来的一律回落到境况表里那个 `calls`。**那不是缺省，
 * 那就是寻常人家那一套本身**——「爹」「娘」「哥」「姐」，
 * 种地的、打猎的、开客栈的、坐堂看诊的没有分别，
 * 在这儿写八遍只会让上面那两格显不出来。
 *
 * 挂在 `Trade`（户籍）上，不挂在 `living`（他过的日子）上，
 * 理由见 `engine/address.ts`——削爵之后日子变了，户籍没变，
 * 而话是在那个户籍底下学会的。
 */
const BY_TRADE: Partial<Record<Trade, string>> = {
  皇室: 'palace',
  王府: 'study',
  官宦: 'study',
}

/** 这样的人家，孩子学的是哪一套话。没有特别的一套就返回 undefined */
export function registerFor(trade: Trade): Register | undefined {
  const id = BY_TRADE[trade]
  return id === undefined ? undefined : REGISTERS.find((one) => one.id === id)
}

/**
 * 有封号的人，别人当面怎么称呼。
 *
 * 「殿下」「世子」跟上面那一套的性质完全不同：它们**带着政治身份
 * 和礼仪距离**，不是普通的亲属称谓。所以它们跟着 `identity` 走，
 * 而 `identity` 是一道旨意就能改的东西。
 */
const HONORIFICS: Readonly<Record<string, string>> = {
  皇子: '殿下',
  公主: '殿下',
  世子: '世子',
  郡主: '郡主',
}

/**
 * 没有封号的人被怎么称呼。
 *
 * 这是全作第二处非分性别不可的地方，理由跟第一处（宗室封号）同源：
 * **称呼语本身带性别**，「公子」落在女孩身上是穿帮。
 * 别处一律不分——不是因为古代女子的人生和男子一样，
 * 而是因为写一半比不写更糟。
 */
const PLAIN: Readonly<Record<Gender, string>> = { 男: '公子', 女: '姑娘' }

/**
 * 别人当面怎么称呼他。
 *
 * 削爵那一卷里，这一格从「殿下」掉到「公子」——两个字就把
 * 整件事说完了。而同一天他开口叫的还是「娘娘」。
 */
export function titleFor(identity: string, gender: Gender): string {
  return HONORIFICS[identity] ?? PLAIN[gender]
}

/** 全库一共有几种带封号的敬称。**门禁拿它报覆盖率，别在那边另抄一张** */
export const HONORIFIC_IDENTITIES: readonly string[] = Object.keys(HONORIFICS)
