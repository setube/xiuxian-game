import type { Bond, Gender, Manner, OriginId } from '@/types/game'

/**
 * 称谓语境。
 *
 * ## 「皇子就该满嘴父皇母妃」是个误区
 *
 * 影视剧把宫廷称谓压成了一套固定词汇，可古代称谓高度依赖
 * **朝代、场合、身份关系**，不能把不同朝代的宫廷叫法混在一起用。
 * 宋代皇室内部的日常称呼其实相当家常：皇子称父亲可以是「爹爹」，
 * 称母亲「娘娘」，兄弟之间按排行叫「大哥」「九哥」，
 * 并不普遍使用「父皇」「皇兄」这一套。清代又明显不同——
 * 「阿哥」本是满语里的兄长称呼，清初用于贵族子弟，
 * 后来才成为皇子的专称，而官方文书里另有「皇某子」的制度化写法。
 *
 * 所以这一层要的不是「给皇子发一套特殊词汇」，而是那句更朴素的话：
 * **一个人管家里人叫什么，取决于他是在哪儿学会说话的**，
 * 以及**他此刻是在跟谁说话、在什么场合说**。
 *
 * ## 这一层为什么非有不可
 *
 * 在它落地之前，四种出身的孩子管爹一律叫「爹」——`calls` 是
 * `content/circumstances.ts` 那张境况表里写死的一个字符串，
 * 而境况跟户籍是**正交**的：境况只管「关系网长什么样」
 * （有没有爹娘、谁把你养大），管不着这家是种地的还是坐龙椅的。
 *
 * 于是童年那一卷里会读到这么一句（这是实测跑出来的，不是设想）：
 *
 *     后来母妃带你去给爹问安。
 *
 * 「母妃」是硬写在正文里的宫廷词，「爹」是插值出来的寻常人家的词，
 * 并排站在同一句话里。**身份是皇子，台词却像普通农户。**
 *
 * ## 三张表，从下往上盖
 *
 * - **教养**（`REGISTERS`）：他在哪儿学会说话的。改不掉。
 * - **爵位**（`RANK_CALLS`）：对方身上有没有封爵，以及此刻在不在行礼。
 *   盖在教养上头——查得到就用它，**查不到落回教养**。
 * - **身份**（`HONORIFICS`）：别人当面怎么称呼他。方向是反的。
 *
 * 「落回」这一条是爵位那张表的全部要害。削爵那天不需要谁去删掉
 * 那声「父王」：父亲的 `rank` 从「亲王」换成一个表里查不到的「宗室」，
 * **那个词自己就失去了依据**，而底下教养给的「父亲」一直在那里没动过。
 * 一句 `{ type: 'family', id: 'father', rank: '宗室' }` 就是全部。
 *
 * ## 称谓有两个方向，而这两个方向的来源不一样
 *
 * - **他怎么称呼别人**（`REGISTERS` + `RANK_CALLS`）跟着**教养**和
 *   **对方是谁**走。教养那一半是小时候学会的，学会了就改不掉——
 *   削爵迁出京城以后，他开口还是那一套，因为没有人能在四十天的路上
 *   把一个人重新教一遍。
 * - **别人怎么称呼他**（`HONORIFICS`）跟着**身份**走。
 *   旨意当天下来，第二天街上就没有人再叫他殿下了。
 *
 * 这两件事在削爵那一卷里同时发生，而且**朝相反的方向脱节**。
 * 跟 `identity`（社会身份）和 `living`（实际生活状态）那一次同构：
 * 一格说变就变，另一格纹丝不动，分开之后才写得出那种别扭。
 *
 * ## 「世子」不是一种亲属称呼，而是一种身份
 *
 * 这句话是整层的分界线，也是 `HONORIFICS` 跟另外两张表分开的理由。
 * 一个人是谁的儿子，跟他被封作什么，是两件独立变化的事：
 * 旨意能除掉封号，除不掉父子。所以解析一句话要问四个格子——
 *
 *     关系　　他是我什么人　　　　　`Bond`
 *     教养　　我是在哪儿学会说话的　`OriginId` → `Register`
 *     爵位　　他身上有没有封爵　　　`Person.rank`
 *     场合　　此刻在不在行礼　　　　`Manner`
 *
 * ——而**不是**去建一张「皇族 = 全部特殊称谓」的表。那种表的问题
 * 不在于写起来麻烦，在于它把上面四格压成了一格：削了爵之后
 * 整张表要么全废要么全留，中间那种「爵位没了，父子还在」写不出来。
 *
 * ## 史料能证明什么，我们又合理化了什么
 *
 * 底下每一个词都带一格 `attested`，**两层严格分开**：
 *
 * - `史料`——引得出出处。「世子」是《礼部志稿》卷十五里的制度身份，
 *   「殿下」「陛下」是历代通行的仪礼称谓。
 * - `合理化`——我们为了游戏语言定的。「父王」「母妃」都在这一层：
 *   《礼部志稿》卷十六证明的是**两套礼并存**（亲王入朝，在朝廷行君臣礼，
 *   至便殿则叙家人礼），不是家人礼那一侧出口的到底是哪两个字。
 *   后世小说把「父王、母妃、皇兄、皇弟」固化成了一套，那是文学表达，
 *   不是明代的固定制度称呼，**不能跟「世子」「殿下」算作同一级**。
 *
 * 分开写的用处不在存档，在于哪天要把这个世界统一到某一朝的礼制上，
 * 要动的只有 `合理化` 那几条，`史料` 那几条原样留着。
 *
 * ## 现在仍然不做的三件事
 *
 * - **时代礼制**：这个世界根本没有朝代设定。「本朝」全库出现过两次，
 *   两次都在注释里（`types/game.ts` 和 `youth.ts` 里那句「本朝女子不应举」），
 *   **正文一个字也没提过朝代**：没有国号、没有年号、没有一条礼制条文。
 *   底下每条注出的朝代因此只是**这个词从哪儿来的**，不是这个世界的年号。
 *   凭空造一张朝代对照表，等于先造阶梯再找楼——这个项目已经吃过一次那种亏。
 * - **分得出伯父和叔父**。传统亲属称谓极细：父之兄称伯父、父之弟称叔父，
 *   母之兄弟称舅父，各有各的词。可 `Bond` 里祖父母、叔伯、姑舅**全在
 *   「亲戚」一格**——这个世界模型压根没记「他是父亲的哥哥还是弟弟」。
 *   在这儿写一张伯父叔父对照表，查的是一个不存在的字段。
 *   要做得先给 `Relation` 添排行，那是另一件事。
 * - **给每种出身铺满一整套称呼**。`kin` 里没写的一律回落境况表的 `calls`。
 *   绝大多数关系在哪套话里都是同一个字，铺满只会让真正不一样的那几格淹掉。
 */

/**
 * 一个称谓的依据。
 *
 * 这一格不是注释，是**判据**：门禁按 `level` 数「史料几条、合理化几条」，
 * 而 `from` 那句话必须自己站得住——写「大概是这么叫的」等于没写。
 * 这条规矩跟别处那条同源：**文档里的因果解释也是判据，也要有出处。**
 */
export interface Attestation {
  /** 史料 = 引得出出处；合理化 = 我们为游戏语言定的 */
  level: '史料' | '合理化'
  /** 史料写书名卷次和朝代；合理化写为什么这么定，以及它软在哪儿 */
  from: string
}

/**
 * 一个人学会的那一套称呼。
 *
 * `kin` 里没写的关系一律回落到境况表那个 `calls`。这不是省事：
 * **绝大多数关系在哪一套话里都是同一个字**，逐条铺满只会让
 * 「哪几个字真的不一样」淹在一片相同的字里。
 */
export interface Register {
  id: string
  /** 这套话是在什么样的人家学的。走查报表用 */
  learntIn: string
  /** 这一套话的依据。整套一条，因为它们本来就是一个地方学的一整套 */
  attested: Attestation
  /** 这套话里，家里各人怎么叫 */
  kin: Partial<Record<Bond, string>>
}

