import { rankCallFor, registerFor, titleFor, type Register } from '@/content/address'
import { useCharacterStore } from '@/stores/character'
import { useHouseholdStore } from '@/stores/household'
import { usePeopleStore } from '@/stores/people'
import type { Bond, Intimacy, Manner } from '@/types/game'

/**
 * 他学的是哪一套话。
 *
 * ## 读的是他生在哪一行，不是他现在过的日子
 *
 * 这一行是整层里最要紧的一个选择，因为「话改不掉」这条性质
 * 全押在它上面。三个候选，两个是错的：
 *
 * - `character.living` 是他**此刻**过的日子。削爵之后它变成 `market`，
 *   于是他一搬进城南那个小院，开口就从「娘娘」变回「娘」——
 *   **一个人的口音不会在搬家当天改掉。** 四十天的路上没有人重新教他说话。
 * - `character.livings[0]` 更不行。`liveAs` 只在**换**日子那一刻记一笔，
 *   出生那一段根本不在数组里；于是第一条恰恰是他**离开**那地方之后的
 *   那一段。拿它当「他在哪长大」，答案永远是「他后来搬去的地方」。
 * - `household.origin` 是他生在哪一行。它掷定就不再动（见 `content/living.ts`：
 *   「家里的籍还是宗室，抚养他的人也还是母妃，可他过的已经不是宫里的日子」）。
 *   **那正是他长大的那个家。**
 *
 * 顺带说一句为什么不是家世那一格（`station`）：削爵那天它从「宗室」
 * 掉到「寻常」，而一个人的口音不会跟着一道旨意改掉。
 * 何况教养分得比家世细——宫里学的是「爹爹」，王府学的是「父亲」，
 * 两家的 `station` 却是同一个值。
 *
 * `scripts/address.ts` 第五节把第一个候选当坏实现喂给同一把尺子：
 * 接上去削爵那一条就会落回寻常人家那套话，判据必须当场红。
 *
 * ## 「逐渐学会」那一层现在不做
 *
 * 一个从民间进王府的人，知道自己是世子，不代表他已经掌握了那套话；
 * 反过来，宫里长大的孩子被贬为庶人，那套话也不会跟着爵位一起除掉。
 * 完整的样子是：**身份事实 → 别人怎么称呼他 → 他自己当下的习惯 →
 * 经过教养 → 逐渐学会。** 中间那两步之间应该有一段时间差。
 *
 * 这一版没做那段时间差，因为**没有内容逼它**：这个世界的出身是
 * 出生那一刻掷定的，没有一条人生会中途换语言环境。硬做出来，
 * 就是一个谁也没走进去过的状态机。
 *
 * 什么时候该做：写出第一卷「他被抱进另一种人家」的内容时。
 * 到那时这个函数要改成读一段带年份的教养史，而不是读一格出身——
 * 而它今天读的这一格，正是那段教养史退化到只有一段时的样子。
 */
export function registerNow(): Register | undefined {
  return registerFor(useHouseholdStore().origin)
}

/**
 * 家里这一种关系，他学着管人家叫什么。
 *
 * ## 两层，上面那层盖下面那层
 *
 * 1. **对方的爵位**（`rank`）+ **此刻在不在行礼**（`manner`）。
 *    王府那位父亲挂着「亲王」，于是家常落成「父王」，礼上落成「王爷」。
 * 2. 查不到就落到**他学的那套话**——王府和官宦一样是「父亲」。
 *
 * 顺序不能倒过来。倒过来的话教养永远赢，爵位那张表等于没写；
 * 而这么排之后，削爵只要把 `rank` 换成一个查不到的值，
 * **那声「父王」自己就退回「父亲」**，不需要谁去删它。
 *
 * ## 为什么爵位在上、教养在下
 *
 * 因为这两层塌的时机不一样。爵位是一道旨意就没的东西，
 * 教养是四十天的路上没人能重新教一遍的东西。
 * 摞成两层，才写得出「爵位没了，父子还在」那种别扭——
 * 压成一张「皇族专用词表」的话，削爵之后要么全废要么全留。
 *
 * ## 返回 undefined 是有意义的答案
 *
 * 它表示这一格上他跟寻常人家没有分别——调用方回落到
 * `Acquaintance.calls`，也就是境况表里那个字。**不在这儿兜底**：
 * 兜底放在这里，「他没学过特别的叫法」和「他学的正好也是这个字」
 * 就分不开了。
 */
export function kinCall(bond: Bond, rank?: string, manner: Manner = '家常'): string | undefined {
  const byRank = rank === undefined ? undefined : rankCallFor(rank, bond, manner)
  return byRank ?? registerNow()?.kin[bond]
}

/**
 * 别人当面怎么称呼他。跟着身份走，一道旨意就能改。
 *
 * 跟上面那个函数朝相反的方向：那个读户籍（改不掉），
 * 这个读 `identity`（说变就变）。削爵那一天两者同时被检验。
 *
 * ## 这一层不接场合
 *
 * `kinCall` 分家常和礼上，这个不分——「殿下」「世子」「郡主」
 * **本身就是身份称谓**，在灶间说和在殿上说是同一个词，
 * 换个场合改的是说不说，不是说成什么。
 * 「世子殿下」那种叠法里，「殿下」是敬语，不是场合标记。
 *
 * 接了场合反而会坏事：那就得给每个封号各写一遍家常版和礼上版，
 * 而两版永远一模一样——一整排永远解析成同一个词的分支。
 */
export function titleNow(): string {
  return titleFor(useCharacterStore().identity, useHouseholdStore().gender)
}

/**
 * **这个人**此刻会怎么称呼你。
 *
 * ## `titleNow` 少问了一件事：谁在叫
 *
 * 16.md 那一节点的正是这个：
 *
 * > 不能写死：`identity = 官员` → 所有人统一叫「大人」。
 * > 同一时刻可以存在多个称呼——邻居「张老爷」，旧友「三哥」，
 * > 下属「大人」，孩子「父亲」。
 *
 * `titleNow()` 只读 `character.identity`，**跟谁在说话无关**，
 * 于是中了秀才那天全村人一起改口，包括你娘。
 *
 * ## 三层，近的盖远的
 *
 *     一　家里人　　不改口。娘、哥、妻子、孩子叫的还是他们一直叫的那个
 *     二　旧交　　　**不称呼**。开口就说事——见下
 *     三　其余人　　按你此刻的身份走 `HONORIFICS`
 *
 * 顺序不能倒：倒过来的话身份永远赢，而那正是这一层要推翻的东西。
 *
 * ## 第二层为什么返回 `undefined`，而不是一个词
 *
 * 头一版我让它返回「你」，想表达「旧友不改口」。可那是个假答案：
 * **旧友叫的是你的名字或小名，而这个世界里玩家没有名字。**
 * 硬凑一个词出来，等于替这个人编了一句他说不出的话。
 *
 * 而 `undefined` 恰恰是真的：**中文里熟人开口本来就不带称呼。**
 *
 *     生人　「相公留步。」
 *     旧交　「你这是打哪儿来？」
 *
 * 后面那句一个称呼也没有，而它比任何称呼都更说明两人的关系。
 * 所以这一层交付的不是一个词，是「**这个人不必称呼你**」这件事——
 * 正文照着它决定要不要在句首放那两个字。
 *
 * ## 这一层落地的是文档里那条硬规则
 *
 * > 身份变化不得删除人物既有经历与关系历史。
 *
 * 而它在代码里的样子恰恰是**前两层没有读 `identity`**：
 * 你考中也好、革了功名也好、削爵也好，第一层第二层一个字不动。
 * 「旧关系不会因为你发迹而消失」不是一句设定，是这两层里没有那个变量。
 *
 * ## 十六年这个数
 *
 * 取的是「从小一起长大」——一个认了你十六年的人，见你的第一眼
 * 是你还光着屁股的时候。半路认识的（掌柜、同僚、路上遇见的）
 * 到不了这个数，他们叫的就是你现在这个身份。
 *
 * 用 `boundFor` 而不是好感：**一个跟你处得不好的发小照样不叫你相公**，
 * 而且那种时候那份不客气更扎人。这一层跟好感无关。
 *
 * @param speakerId 说话的那个人。不在人口册上的（陌生人）按第三层
 * @param manner 场合。礼上一律走身份那一层——**当着众人，你哥也得叫你相公**
 * @returns 他称呼你的那个词；`undefined` 表示**他开口不必称呼你**
 */
export function callMeBy(speakerId: string, manner: Manner = '家常'): string | undefined {
  const people = usePeopleStore()
  const character = useCharacterStore()
  const household = useHouseholdStore()
  const byTitle = titleFor(character.identity, household.gender)

  /*
   * 场合先问。
   *
   * 这一条是三层之上的：**祠堂里、公堂上、有外人在的席面上，
   * 家里人也得用那个称呼**。明代礼法在这一点上很硬，
   * 而它恰恰让第一层更有分量——正因为外头得那么叫，
   * 关起门来那声旧称才是私底下的东西。
   */
  if (manner === '礼上') return byTitle

  const bonds = people.bondsWith(speakerId)

  // —— 一、家里人不改口 ——
  const call = HOUSE_CALLS.find(([bond]) => bonds.includes(bond))
  if (call) return call[1](household.gender)

  // —— 二、认识够久的，开口不称呼 ——
  if (bonds.some((bond) => people.boundFor(speakerId, bond) >= OLD_ENOUGH)) return undefined

  // —— 三、其余人按你此刻的身份 ——
  return byTitle
}

/**
 * 认识多少年算「从小」。
 *
 * 十六年。到这个数的人见过你还不成人的样子，而那件事**改不掉**——
 * 这正是它跟身份的分别：身份是一道旨意、一张榜就能换的，
 * 「他见过你小时候」谁也拿不走。
 */
const OLD_ENOUGH = 16

/**
 * 家里人叫你什么。
 *
 * 排在前面的先命中——一个人可能同时是好几样（姐姐也是抚养人），
 * 那就按最贴身的那一层叫。
 *
 * ## 兄姐爹娘不在这张表里，那不是漏写
 *
 * **他们叫的是你的名字，而这个世界里玩家没有名字。**
 * 硬填一个词进去就是替他们编话。他们落到第二层（`undefined`）——
 * 而那正是对的：**你哥开口不会先叫你一声。**
 *
 * 表里这几行是反过来的：儿女叫「爹」、妻子叫「当家的」、
 * 弟妹叫「哥」、徒弟叫「师傅」——这些**不是名字的替代品，
 * 就是那个称呼本身**，一辈子不换。
 *
 * ⚠️ 这张表**一个字也不读 `identity`**，那是它存在的全部理由。
 * 哪天有人想在这里加一行「他中了秀才之后妻子改叫相公」，
 * 先回去读 16.md 那句：身份变化不得删除既有关系。
 */
const HOUSE_CALLS: readonly [Bond, (gender: '男' | '女') => string][] = [
  ['子', (g) => (g === '男' ? '爹' : '娘')],
  ['女', (g) => (g === '男' ? '爹' : '娘')],
  ['配偶', (g) => (g === '男' ? '当家的' : '娘子')],
  ['弟', (g) => (g === '男' ? '哥' : '姐')],
  ['妹', (g) => (g === '男' ? '哥' : '姐')],
  ['徒', () => '师傅'],
]

