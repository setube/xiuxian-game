import { randomBetween } from './random'

/**
 * 天年。
 *
 * ## 为什么人生需要一个终点
 *
 * 上一版没有终点，因为它根本不需要——十六岁那年在渡口收尾，
 * 收尾那一卷演完就 `finish()`。**「十六岁没修上仙就结束」这条规则
 * 一旦拿掉，主循环立刻变成一个不会停的圈**：年表抽事、日常耗时、
 * 再抽事，一百二十岁的人还在地里割草。
 *
 * 所以取消那条规则的同时必须给出另一个终点，而唯一诚实的那个是：
 * **这个人不在了。**
 *
 * ## 掷定，不是算出来的
 *
 * 天年跟 `root`（修行资质）走同一条纪律：**出生那一刻就定了，
 * 而这个人一辈子不会知道它是多少**。玩家也看不见——面板上没有它，
 * 存档里有，但那是给引擎用的。
 *
 * 它跟出身完全无关。王府的孩子和农户的孩子在这一掷上平等，
 * 跟根骨那一掷是同一处平等：凡间的一切在这里都不作数。
 * 唯一影响它的是身子骨——那不是家世，那是这具身体本身。
 *
 * ## 为什么下限是四十出头，而不是三岁
 *
 * 真实的古代人口里，夭折占死亡的极大一块。这里**故意不那么掷**：
 * 一局游戏从出生演到死，三成的人生在五岁结束，玩家读到的不是历史，
 * 是一个反复重开的抽奖机。
 *
 * 早夭因此不是「概率里没抽中」，而是一件**至今没有内容的事**——
 * 它该由某一卷具体的病、某一年具体的荒写出来，那时候用 `lifespan` 效果
 * 把天年削到当年（`engine/effects.ts` 里那一条）。先造一个夭折概率摆着，
 * 等于先造阶梯再找楼。
 *
 * ## 修行为什么在这里露面
 *
 * 「修仙是一条极其稀有、风险极高、但可能改变生命长度与世界认知的道路」——
 * **改变生命长度**这半句必须落到一个真实存在的量上，否则它只是一句话。
 * 那个量就是这里的天年，而 `{ type: 'lifespan' }` 是唯一能动它的东西。
 * 一个人修成炼气，他多出来的年头是从这里加的，不是从别处凭空来的。
 */

/** 掷天年的基准区间。中位数落在六十几，跟「七十而终」那条时间轴对得上 */
const SPAN_MIN = 52
const SPAN_MAX = 82

/**
 * 身子骨能挪动天年多少。
 *
 * 上下各十年：底子最差的活到四十出头，底子最好的能到九十开外。
 * 这个跨度是有意留宽的——它是全作里**唯一**由出生那一掷决定的寿数差异，
 * 此后的加减全靠这个人自己经历了什么。
 */
const BODY_PIVOT = 50
const BODY_PER_YEAR = 5

/**
 * 掷定这一世能活多少年。
 *
 * @param body 身子骨的隐藏刻度，0–100。它已经把体质叠进去了
 *   （见 `stores/character.ts` 的 `withConstitution`），所以这里不再问体质
 */
export function rollSpan(body: number): number {
  const base = randomBetween(SPAN_MIN, SPAN_MAX)
  return Math.max(1, base + Math.round((body - BODY_PIVOT) / BODY_PER_YEAR))
}

/**
 * 到了吗。
 *
 * 用 `>=` 而不是 `===`：日常一次能耗掉一到三年，
 * 天年那个数很容易被跨过去。判等的话，跨过去的人就再也不会死了。
 */
export function isSpent(age: number, span: number): boolean {
  return age >= span
}
