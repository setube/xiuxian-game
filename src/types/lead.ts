import type { Condition } from './game'

/**
 * 一条关于修行的消息。
 *
 * ## 修行的第一关不是学不会，是不知道去哪找
 *
 * 一个凡人听说这世上有那种人之后，他能做的只有一件事：**打听**。
 * 而他打听到的东西里，绝大多数是假的——说书人编的、
 * 江湖骗子的招牌、以讹传讹传成另一样东西的。
 *
 * 他分不出来。他手里没有任何工具可以分辨，
 * 唯一的办法是**跑一趟看看**，或者**听到第二个人说同一件事**。
 *
 * ## 真假是世界事实，玩家永远看不到
 *
 * 这跟山道上那个人、货郎摊上那册书是同一套：
 * `truth` 写在数据里，玩家读到的只有 `says` 和他自己记下的 `believes`。
 * 他会带着几条假线索走很多年，而其中一条可能一辈子也没被戳破。
 */
export interface Lead {
  id: string
  /**
   * 这条消息究竟是什么。**玩家永远看不到这一行。**
   *
   *     真　　确有其事，而且指向一处真的地方
   *     半真　方向对，细节错。跑过去会发现不是那么回事，
   *           但不是白跑——它旁边可能有别的东西
   *     假　　彻头彻尾。说书人编的，或者有人拿它骗钱
   */
  truth: '真' | '半真' | '假'
  /** 从哪儿听来的。同一件事从两个不相干的人嘴里出来，分量完全不同 */
  from: string
  /** 他听到的那一句 */
  says: string
  /** 他会怎么记下来。可能跟事实差很远 */
  believes: string
  /** 什么光景下才听得到。**只写世界条件，不写念头** */
  requires?: readonly Condition[]
  weight: number
  /**
   * 它指向哪儿。
   *
   * 真线索和半真线索才有。两条线索指向同一处，
   * 这件事本身就是一种验证——**而那是玩家唯一能用的工具。**
   */
  points?: string
}

/** 跑一趟之后 */
export type Following =
  /** 那地方确实在，而且不像寻常地方 */
  | '对上了'
  /** 那地方在，可是跟说的不一样 */
  | '不是那么回事'
  /** 什么也没有。有时候连那个地名都是编的 */
  | '扑了个空'
  /** 有人在那儿等着他，而等的不是好事 */
  | '被人骗了'

/** 站到门前之后 */
export type AtTheDoor =
  /** 他自己没有进去 */
  | '没进去'
  /** 进去了，人家收了 */
  | '收下了'
  /** 进去了，人家看了他一眼，摇头 */
  | '没收'
