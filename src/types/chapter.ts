import type { Effect, LifeEvent, SceneLibrary } from './game'

/**
 * 一章能被叫出来的方式。
 *
 *     年表　这一章自己的事件被 pickEvent 抽中
 *     日常　lifeRoutine 把某个阶段映射到了这一章的某一卷
 *     收尾　lifeFinale 指着这一章
 *
 * 「别的章跳进来」不在这里，它记在跳出去那一章的 `to` 上——
 * 一条边只写一遍，两头对不上就是有人只改了一边。
 */
export type ChapterCall = '年表' | '日常' | '收尾'

/**
 * 一章。
 *
 * ## 为什么内容要多这一层
 *
 * 从前这一层是隐式的：`index.ts` 里十七行 spread 把所有卷摊平成一个大字典，
 * 章的边界就此消失。门禁于是只能从摊平的数据里**猜**结构——
 * 「这一卷有没有入边」要把年表、日常、收尾、跨卷跳转全扫一遍才答得上来。
 *
 * 猜得越多，门禁就越要懂剧情。再往下加几道，`verify.ts` 会长成半个编辑器。
 *
 * 所以拓扑改成显式声明：**章自己带着卷和事件，`index.ts` 从这里派生**，
 * 而门禁只做一件事——把声明和实现对一遍。
 *
 * ## 手写的那几个字段才是它的价值
 *
 * `scenes` 和 `events` 是内容本身，`id` 是名字，这些抄不错。
 * 真正有分量的是 `called` / `to` / `age` / `purpose` / `marks` 五个：
 * 它们是**人写下来的意图**，而不是从数据里推出来的摘要。
 * 推出来的摘要永远不会红——改了实现它跟着变，什么也证明不了。
 *
 * 写下来就不一样了。悄悄多接一条跨章的跳转，`to` 对不上，红；
 * 把某件事的年龄窗口往外拉一岁，`age` 兜不住，红；
 * 把一章改到不再干原来那件事，`marks` 落空，红。
 * 要绕过它得手动去改这份声明——**而改的那一刻，人就看见自己在做什么了**。
 */
export interface Chapter {
  /**
   * 章名。跟卷名的前缀不一定一样——`seeking` 这一章的卷叫 `seek:*`，
   * `hardship` 的卷叫 `debt:*`。前缀是写剧本时顺手起的，章名跟着文件走。
   */
  id: string
  /** 这一章的卷 */
  scenes: SceneLibrary
  /** 这一章的年表事件。`routine` 那一章是空的——它不由年表叫出来 */
  events: readonly LifeEvent[]
  /** 怎么被叫出来。一章至少要有一种，一种也没有就是写好了没接上 */
  called: readonly ChapterCall[]
  /**
   * 这一章会把人送进哪些别的章，写章名。
   *
   * 全库现在只有一条这样的边（`day` → `encounters`）。**正因为少，
   * 多出来一条才该被看见**：绕过收尾直接跳进 `riverman` 那种事，
   * 前几道门禁全都放行——跳转有效、有入边、条件也不缺。
   */
  to: readonly string[]
  /**
   * 这一章的年表事件该落在哪几岁之间，闭区间。
   *
   * 守的是章的年龄定位，不是逐件事件的窗口：往里收不红，越出去才红。
   * 「有人把某件事的窗口悄悄延后一年」是这一格唯一想抓的东西——
   * 那种改动会让一整章挪到人生的另一段上去，而没有任何别的地方会吭声。
   */
  age: readonly [number, number]
  /**
   * 这一章为什么存在。
   *
   * 不是剧情概要——那是上头那行注释的活。这里写的是**结构目的**：
   * 它在这套人生模型里顶什么用，少了它哪一层会塌。
   *
   * 写它是为了几年以后。那时内容有几百件，每一件单看都合理，
   * 而「这一卷当初是干什么的」只剩这几行能回答。没人答得上来的内容
   * 不会被删，只会被绕开——然后新写的东西在旁边重做一遍同样的事。
   */
  purpose: readonly string[]
  /**
   * `purpose` 在数据里的影子：这一章必须真的落下这几种效果。
   *
   * 只写招牌产出，不写全部产出。`time` / `attribute` / `flag` 几乎人人都有，
   * 写进来等于没写；要写的是**删掉它这一章就不成立**的那几种——
   * 打听那一章不产 `ask`，机缘那一章不产 `encounter`，
   * 那它已经不是原来那一章了，只是没人吭声。
   *
   * 这一格也完全可以从数据里算出来，而算出来的版本永远不会红。
   * 它的意义正在于是手写的：`purpose` 说的话没法验，`marks` 能验，
   * 两者一起，那句话才不至于慢慢变成谁也不看的文案。
   */
  marks: readonly Effect['type'][]

  /**
   * 这一章落的身份，是**可以停留的终点**，还是**正在做的一件事**。
   *
   * 只有 `marks` 里含 `identity` 的章要填。
   *
   * ## 为什么要人标——因为机器判不出来
   *
   *     生员　中了秀才就是一辈子的秀才　　　　　终点
   *     匠人　出了师就是匠人　　　　　　　　　　终点
   *     学童　**不念书了就不是学童**　　　　　　正在做的事
   *     伙计　**不在铺子里了就不是伙计**　　　　正在做的事
   *
   * 分界在**语义**里：「学童」这个词自己含着一个终止条件，「生员」没有。
   * 而这件事**代码里看不出来**——两者都是一个字符串，都由某一卷落下，
   * 都可能没有下家。所以它必须是人标的一格。
   *
   * ## 标它是为了守住什么
   *
   * 2026-09-08 实测：**450 世的人死的时候身份栏还写着「学童」**——
   * 念了书、没考中，而没有任何一卷内容接手他。这是「只设不改」的第三次发作
   * （前两次是「学徒」和「伙计」）。
   *
   * 而**不能靠「到死还挂着的比例」一刀切**：`生员` 和 `匠人` 那个比例也高，
   * 可它们高得对。判据得先知道哪些该低、哪些本来就该高——**这一格就是那个先验**。
   *
   * `scripts/standing-identity.ts` 拿它两头问：标了「正在做的事」的问到死比例，
   * 标了「终点」的问有没有人给它写下家（**那说明标错了，或者那一卷写错了**）。
   * 人标的东西也会腐烂，所以两头都要问。
   */
  identityKind?: '终点' | '正在做的事'
}
