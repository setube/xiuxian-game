import type { Condition, GameTime } from './game'

/**
 * 念头。
 *
 * ## 为什么不是「勇敢 72 / 好奇 81 / 野心 43」
 *
 * 那样做的话，人的内心就变成了一张给玩家看的数据库——
 * 而这跟前面几轮反复守住的立场是冲突的：**别人怎么看你不给数字，
 * 世界什么光景不给数字，那么你自己是什么人更不该给数字。**
 *
 * 所以念头做成跟日录同构的东西：它不是一个数，是**一串他做过的事**。
 *
 *     十岁　　你总喜欢站在高处看村子。
 *     十二岁　镇上来了商人，你问的都是远处的事。
 *     十五岁　家里出事之后，你第一次认真想过离开。
 *
 * 「我好像总是这样做」这句话，得让玩家自己从那一串里读出来，
 * 不是引擎跳出来告诉他。
 *
 * ## 三个阶段，念头不直接变成任务
 *
 *     一、埋着　　什么也不显示，只在日录里留下痕迹
 *     二、反复　　带某些标记的日子里，正文多出一句
 *     三、明白　　他自己说出来了，人物面板上出现那句话
 *
 * 中间那一层是这套东西的关键。念头一旦冒出来就变成
 * 「【任务：成为郎中】」，那是任务系统，不是一个人的一生。
 * 真实的样子是：看见郎中会多看一会儿，路过药铺会进去问一句，
 * 有人谈药他会记住——**很多年之后他才发现自己一直在做这件事。**
 *
 * ## 大多数人一辈子没有明确的方向
 *
 * 这一条跟「大多数行动没有机缘」是同一条。
 * 如果每个人最后都长出一个「我要改变命运」，凡人生活就失去了真实性。
 * 好好过日子、养家、把孩子拉扯大、平安过完一生——**那不是失败路线。**
 */

/** 一个念头此刻长到哪一步 */
export type LeaningStage =
  /** 埋着。他自己都还没意识到 */
  | '埋着'
  /** 反复。他开始总是往那边看，但他说不出为什么 */
  | '反复'
  /** 明白。他自己把它说出来了 */
  | '明白'

/** 念头长起来的一刻。攒成一串，就是他为什么会变成这样的人 */
export interface LeaningMoment {
  at: GameTime
  /** 那一刻他做了什么。写的是行为，不是心理描写 */
  text: string
}

/** 他心里正在长的一个念头 */
export interface LeaningState {
  id: string
  /** 有多结实。**玩家永远看不到这个数** */
  weight: number
  /**
   * 他最想的时候有多想。
   *
   * 念头会退，可**退回去跟从来没有过是两回事**——
   * 一个想走了三年最后留下来的人，跟一个从没动过这个念头的人，
   * 不是同一个人。没有这个字段就分不出他们俩。
   */
  peak: number
  /** 它是从哪些事上长出来的 */
  moments: LeaningMoment[]
  /** 他是哪一年把它说出来的。没说出来就是 null */
  namedAt: GameTime | null
}

/** 一种念头的定义 */
export interface Leaning {
  id: string
  /**
   * 他终于把它说出来时的那句话。
   *
   * 第一人称，因为这一句是**他自己说的**，不是系统贴的标签。
   */
  says: string
  /** 到了「反复」这一档，人物面板上那一句还很含糊的话 */
  stirring: string
  /**
   * 到了「反复」这一档之后，某些日子里会多出来的一句。
   *
   * 这是「念头在后续选择里反复出现」的落点——**不加选项，不加任务，
   * 只在他本来就会做的事情上多一句话。** 玩家会先觉得这句话眼熟，
   * 很久以后才反应过来自己一直在做这件事。
   */
  echoes: readonly { tags: readonly string[]; text: string }[]
}

/**
 * 一件事点着了一个念头。
 *
 * 火种不自带内容——它寄生在**已经发生过的事**上：
 * 日录里的标记、身上的旗标、认识的人、知道的事。
 * 这一条是有意的：念头必须从人生里长出来，
 * 不能是另一套平行的剧本。
 */
export interface Spark {
  id: string
  /** 点着哪个念头 */
  leaning: string
  /** 加多重 */
  weight: number
  /** 什么光景下才点得着 */
  requires?: readonly Condition[]
  /** 或者：这一天带着这些标记 */
  tags?: readonly string[]
  /** 那一刻他做了什么。进念头的 moments，也进日录 */
  text: string
  /** 同一个火种一辈子只点一次。默认可以反复点 */
  once?: boolean
  /**
   * 点着的机会，0–1。不写就是每回都点。
   *
   * **这一条是长尾的发条。** 没有它，凡是天天做的事都会稳稳地
   * 往上加，于是人人都会长出方向来——而真实的样子是：
   * 同样去地里干活，绝大多数时候心里什么也没留下，
   * 只有偶尔那一次会。
   */
  chance?: number
}

/**
 * 一个机会。
 *
 * ## 这一册最要紧的一条规矩：念头不得创造世界事实
 *
 * 商队本来就要走，短工本来就在招，那条道本来就在那儿。
 * **世界不因为玩家想要什么而配合玩家。**
 *
 * 所以 `requires` 里只许写世界条件——年景、年纪、身上的旗标、
 * 认识的人。一个念头进不了这里，一个字也进不了。
 * 这一条做成了走查门禁：机会的出现条件里若引用了念头，非零退出。
 *
 * 念头只改一样东西：**他怎么读这个机会。**
 *
 *     没有念头的人　　镇上有人招短工，管饭。
 *     想离开的人　　　你忽然想到，那支商队要往很远的地方去。
 *
 * 选项一个没多，世界一寸没变。**变的只是他注意到了什么。**
 */
export interface Opening {
  id: string
  /**
   * 什么光景下这个机会才在。
   *
   * **只许写世界条件。** 一个念头进不了这里——
   * 商队本来就要走，不是因为他想走才来的。
   */
  requires?: readonly Condition[]
  /**
   * 谁都读得到的那句。
   *
   * 这是这个机会**本来的样子**，跟玩家心里想什么无关。
   */
  plain: string
  /**
   * 心里存着某个念头的人，会多读出来的那一句。
   *
   * 只在念头到了「反复」或「明白」时才出现——**埋着的时候什么也不多**，
   * 因为那时候他自己都还没意识到。
   */
  readings: readonly { leaning: string; text: string }[]
}

/**
 * 反向的火种：一件事把某个念头压下去了。
 *
 * **念头不能只会越来越强。** 一个人想离开家乡十年，可能最后真的走了，
 * 也可能因为爹娘老了留下来，也可能出去一趟发现外面并不像自己想的那样。
 *
 * 这跟认知系统里那条「解释可以往下掉」是同一个立场：
 * 玩家对世界的认识会改变，**玩家对自己想要什么的认识也会改变。**
 */
export interface Damper {
  id: string
  /** 压哪个念头 */
  leaning: string
  /** 压下去多少 */
  weight: number
  /** 顺带点着的那个。想离开被压下去的时候，往往是「想守着」冒上来 */
  instead?: { leaning: string; weight: number }
  requires?: readonly Condition[]
  tags?: readonly string[]
  chance?: number
  once?: boolean
  /** 那一刻他做了什么。跟火种一样：写行为，不写心理 */
  text: string
}
