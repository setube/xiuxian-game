/**
 * 人生事件：某一年可能落到你头上的一件事。
 *
 * 这里是本作最容易翻车的地方——事件池 + 掷骰 = 随机事件模拟器。
 * 三条约束把它拉回「人生」：
 *
 * 1. **链优先**。写了 chain 的事件排在散事件前面。父亲欠了债，
 *    接下来该来的是他去外地做工，不是随机撞上的一场庙会。
 * 2. **条件即因果**。事件靠 requires 串起来，前一件事留下的旗标
 *    是后一件事的入场券。链条是长出来的，不是编号排出来的。
 * 3. **窗口不是日程**。window 只说「这事最早最晚可能在几岁发生」，
 *    条件不满足就永远不发生——很多人的一生里它确实没发生过。
 */
export interface LifeEvent {
  /**
   * 这件事可以反复发生。
   *
   * 默认 false——**大多数人生事件一辈子只来一次**：父亲不会欠两次同一笔债，
   * 你不会在同一年被同一个先生收两次。
   *
   * 但「一天」不一样。一个人过的日子成千上万，
   * 它要是也只能发生一次，日录里就只会躺着孤零零的一条，
   * 而「多年以后才明白」永远不会有机会出现。
   */
  repeatable?: boolean
  id: string
  /** 可能发生的年龄闭区间 */
  window: { from: number; to: number }
  requires?: Condition[]
  /** 因果链的名字。同链事件优先于散事件 */
  chain?: string
  /** 同级候选中的相对权重，缺省为 1 */
  weight?: number
  /** 要演的那一卷，写法同 next */
  scene: string
}

