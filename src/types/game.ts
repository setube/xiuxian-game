/**
 * 人生阶段。
 *
 * 年龄只是刻度，阶段才决定这一年你可能撞上什么。
 * 「私塾」不在其列——不是所有人都读得起书，
 * 那是「启蒙」这一段里的一条岔路，不是人人必经的一站。
 */
export type LifeStage = '幼年' | '启蒙' | '少年' | '成年'

// ============================================================
// 角色 · 认知层
// ============================================================

/** 角色会去打量自己的几个方面。 */
export type AspectKey = 'body' | 'learning' | 'cultivation' | 'root'

/**
 * 他人之言。
 *
 * 认知层的关键：一名炼气修士说你「不错」，宗门执事说你「中下」，
 * 两句话都会留在这里。玩家日后翻看，才会发现当初那个「不错」
 * 根本不是自己理解的意思。所以评价只增不改。
 */
export interface AspectClaim {
  id: string
  /** 谁说的：「一名炼气修士」「宗门执事」 */
  source: string
  /** 他说了什么 */
  text: string
  /** 你对这句话的理解——通常是不理解 */
  doubt?: string
  at: GameTime
}

// ============================================================
// 观察：真实属性 → 观察能力 → 观察结果 → 语言 → 玩家理解
// ============================================================

/**
 * 一把尺子。
 *
 * 它量的东西**不等于任何一个真实属性**——这是整套系统的立足点。
 * 私塾先生眼里的「聪慧」，记性占七成、悟性占三成，
 * 因为他只能从背书快慢去推断；修士说的「悟性」才是那一样单独的东西。
 *
 * 于是「先生说的聪明和修士说的悟性根本不是一回事」不再是一句设定，
 * 而是两把权重不同的尺子量出来的两个数。
 */
export interface Lens {
  /** 这把尺子的名字，只用于调试与走查 */
  id: string
  /** 量的是哪几样真实属性，各占多重 */
  weights: Partial<Record<AttributeKey, number>>
  /** 量出来的话挂到哪一面下 */
  aspect: AspectKey
}

/**
 * 一个会开口评价你的人。
 *
 * `acuity` 是他的判断力，不是他的地位：
 * 乡下郎中看身体比宗门长老准，长老看资质比郎中准。
 * 判断力低的人不是会说谎，是会看错——他说的是他真看到的。
 */
export interface Observer {
  id: string
  /** 玩家会怎么称呼他 */
  name: string
  /** 他会看哪几样，各有多准 */
  readings: readonly Reading[]
}

export interface Reading {
  lens: Lens
  /**
   * 判断力，0–100。
   *
   * 它决定观察结果偏离真值多远。一个炼气修士看「悟性」只有五十几分的准头，
   * 所以他说「悟性一般」的时候，可能真的看错了——
   * 而玩家永远不会知道他看错了。
   */
  acuity: number
  /** 他管这把尺子叫什么：先生叫「聪慧」，修士叫「悟性」 */
  calls: string
  /** 分档措辞。同一个数，不同的人说法不同 */
  phrasing: readonly Phrase[]
  /** 玩家听完这句话之后的困惑。不写就是听懂了 */
  doubt?: string
}

/** 一档措辞。自上而下取第一个够得着的 */
export interface Phrase {
  atLeast: number
  says: string
}

export interface Aspect {
  /** 角色的自述。null 表示他连这回事都不知道 */
  self: string | null
  claims: AspectClaim[]
}

export type Aspects = Record<AspectKey, Aspect>

/** 人际。affinity 为 -100（仇怨）至 100（生死之交），同样只用于判定。 */
export interface Relationship {
  id: string
  name: string
  affinity: number
  note?: string
}

/**
 * 随身之物。
 *
 * name 是你此刻会怎么称呼它，不是它究竟是什么。
 * 山道上捡的那本书，在你眼里很多年都只是「一册旧书」；
 * 直到某个修士瞥了一眼说出它的名字，它才变成「炼气法门」——
 * 东西一直没变，变的是你。改名靠 reveal 效果，见下。
 */
export interface InventoryItem {
  id: string
  name: string
  count: number
  /** 量词：枚、册、把…… */
  unit: string
  note?: string
  /** 曾被人点破过。面板据此标出「原先你叫它……」 */
  formerName?: string
}

// ============================================================
// 世界认知
// ============================================================

export type KnowledgeCategory = '世事' | '修行' | '地理' | '人物' | '器物'

/**
 * 你对一件事知道到什么程度。
 *
 * 「知道」和「不知道」两档远远不够。一个人从没听说过修士，
 * 到听人提过一嘴，到亲眼见过却完全不懂，到自己有个猜测，
 * 到确信，到亲身验证——这中间隔着很多年。
 *
 * 这一层是后面「为什么拿到功法却不会修炼」的地基：
 * 他手里那册书是真的，可他对「炼气」这件事还停在「听说过」，
 * 中间那几档没走完，书就只是纸。
 */
/**
 * 能打听的事。
 *
 * 定义在这里而不是 content 层，因为 Effect 要引用它——
 * 剧本写 `{ type: 'ask', about: '年景' }` 时得有类型可查。
 */
export type Topic = '年景' | '世道' | '生人' | '家里' | '修士'

/**
 * 认知的三根轴。
 *
 * 从前这三样揉在一个 `grasp` 字段里（听说/见过/猜想/确信/亲历），
 * 而那道梯子其实**混了两个不同的轴**：听说、见过、亲历说的是
 * 他跟这件事离得多近；猜想、确信说的是他形成了什么样的解释。
 * 两者根本不在一条线上——**你可以亲眼见过一样东西，却完全不明白那是什么。**
 *
 * 拆开之后，这些格子全部合法：
 *
 *     听说 + 猜想 + 错　　道听途说，自己编了个解释
 *     见过 + 确信 + 对　　他看见了，而且看懂了
 *     亲历 + 确信 + 错　　他亲手做过，仍然把因果想反了
 *     亲历 + 未理解　　　　他就在场，可他到今天也说不出那是什么
 *
 * 三根轴各有各的走法，这是最要紧的一条：
 * **接触只能往上，解释可以往下。**
 */

/** 接触方式：他跟这件事离得多近。只能往上走——亲眼见过之后不会退回「只是听说」 */
export type Contact =
  /** 听人说起过 */
  | '听说'
  /** 亲眼见过 */
  | '见过'
  /** 亲身经历、亲手做过 */
  | '亲历'

/**
 * 解释状态：他对这件事形成了什么样的说法。
 *
 * **可以往下掉。** 一句「不是那么回事」就能让一个确信多年的人
 * 重新变得不敢肯定——而这跟他有没有弄明白是两回事，
 * 动摇之后他往往什么也没弄明白，只是不再笃定了。
 */
export type Interpretation =
  /** 知道有这么件事，可他说不出那是什么 */
  | '未理解'
  /** 有了自己的猜测。可能是错的 */
  | '猜想'
  /** 他笃定就是这样。可能仍然是错的 */
  | '确信'

/** 这条认知是怎么走到这一步的 */
export type Turn =
  /** 头一回知道有这么件事 */
  | '初识'
  /** 更笃定了，或者离得更近了 */
  | '加深'
  /** 被说动摇了。他没弄明白什么，只是不再敢肯定 */
  | '动摇'
  /** 有人给了另一种说法，跟他原来那个并排放着 */
  | '有了别的说法'
  /** 他终于弄明白了 */
  | '弄明白了'

/** 这条认知在某一刻的样子。攒起来就是他理解这件事的全过程 */
export interface KnowledgeMoment {
  at: GameTime
  /** 那时候他会怎么说这件事 */
  summary: string | null
  contact: Contact
  interpretation: Interpretation
  how: Turn
}

/**
 * 见闻。玩家「知道」某件事，本身就是一种游戏状态。
 *
 * `summary` 是他此刻会怎么描述这件事——**同一个条目在不同的状态下，
 * 说法完全不同**：
 *
 *   听说 · 未理解：有人说这世上有能飞的人。多半是编的。
 *   见过 · 未理解：你亲眼见过一个。他站在船头，水面不动。你不知道那是什么。
 *   见过 · 猜想　：他们大概是修行了什么法门。
 *
 * 所以变化不是「补充细节」，是**换一句话**。而旧的那句不会消失，
 * 它留在 `history` 里——**认知历史本身就是内容**，
 * 一条一路改到「对」的知识条目，跟一个人真实的理解过程毫无关系。
 */
export interface KnowledgeEntry {
  id: string
  title: string
  /** 他此刻会怎么说这件事。null 表示只记住了个名字 */
  summary: string | null
  contact: Contact
  interpretation: Interpretation
  category: KnowledgeCategory
  learnedAt: GameTime
  /**
   * 这条其实是错的。
   *
   * **玩家看不见这个标记**——他若知道自己错了，那就不叫错了。
   * 它只供日后打脸用：某天他亲眼看到真相，才会有一次
   * 「原来当年老丈说的不对」。
   *
   * 分两类，`因果` 比 `事实` 更持久：
   * 事实错误容易撞破（他亲眼看到北边没打仗），
   * 因果错误却可能跟他一辈子——他验证了「北边的人在南逃」，
   * 但仍然以为那是因为兵灾。
   */
  mistaken?: '事实' | '因果'
  /**
   * 一个还没被他采信的说法。
   *
   * **它不覆盖原来那句，是跟原来那句并排放着的。**
   * 有人告诉他「那些人不是江湖人」，他没法立刻接受，
   * 但从此心里有了两个版本——这才是被人说动之后的真实样子，
   * 而不是脑子里那条记录被静悄悄地换掉。
   */
  rival?: string
  /** 这条认知一路是怎么变的。新的追加在后，旧的绝不删 */
  history: KnowledgeMoment[]
}

export type FlagValue = boolean | number | string

/**
 * 世界的一处征象。
 *
 * 这是「世界状态 → 玩家可观察到的现实」那一步的产物。
 *
 * 玩家永远看不到 `grain = 138`，他看到的是「米价比往年贵了许多」。
 * 但这**不只是把数字换个说法**——征象有三条性质，缺一不可：
 *
 * 1. **不是人人都看得见。** 农户看得出今年雨水不对，城里孩子看不出；
 *    商户一眼知道进货的路断了，农户只知道盐贵了。
 * 2. **不精确。** 「贵了许多」对应的是一段区间，不是一个数。
 *    两个不同的粮价可能给出同一句话。
 * 3. **可能被读错。** 街上多了外乡人——是来了商队，还是逃荒的？
 *    玩家得自己判断，而且可能判断错。
 *
 * 三条合起来才是「玩家自己建立世界模型」，而不是「界面换了种说法」。
 */
export interface Sign {
  id: string
  /** 玩家读到的那句话 */
  text: string
  /**
   * 他可能因此产生的理解。
   *
   * 留空表示这句话本身就够明白了。写了的话，
   * 它是玩家**自以为**看懂了的东西——未必对。
   */
  reading?: string
  /** 它其实来自哪个刻度。只进走查，不上界面 */
  from: RegionKey
  tone?: InkTone
}

/** 编年：人生大事记，与逐字正文分开，供回看这一生。 */
export interface ChronicleEntry {
  id: string
  time: GameTime
  text: string
  tone?: InkTone
}

// ============================================================
// 世界
// ============================================================

/**
 * 一个府此刻的光景。
 *
 * 这几个数跟 Attributes、standing 一样是隐藏刻度，**绝不上界面**。
 * 玩家读到的是「今年的米比去年贵了一半」，不是「粮价 168」。
 *
 * 它们随时间自己变，玩家不在场也照变——这是「世界」和「玩家身边的一圈剧情」
 * 的分界线。玩家出生在第九年的江陵府，那个府在第九年是什么样子，
 * 是前面八年一点一点变成的。
 */
export interface RegionState {
  /** 雨水。50 是常年，低了是旱，高了是涝 */
  rain: number
  /** 收成。50 是常年 */
  harvest: number
  /** 粮价。100 是常年 */
  grain: number
  /** 治安。50 是常年，低了路上不太平 */
  order: number
  /** 疫病。0 是没有 */
  plague: number
}

/** 世界状态的键。Condition 用它来问「这个府现在什么光景」 */
export type RegionKey = keyof RegionState

/**
 * 世界自己会发生的一件事。
 *
 * 跟 LifeEvent 的分别是根本性的：
 * LifeEvent 是**落到玩家头上**的事，WorldEvent 是**发生在世界上**的事。
 * 玩家可能碰上，也可能一辈子不知道。
 *
 * 铁律（第 11 条）：**世界事件只改条件，不替玩家决定结果。**
 * 旱灾把粮价推上去，但「你家因此卖了地还是借了债」是玩家那一层的事，
 * 世界这一层不管。
 */
export interface WorldEvent {
  id: string
  /** 因果链的名字。同链的事排在散事件前面 */
  chain?: string
  /** 什么光景下它会发生 */
  when: Partial<Record<RegionKey, { atLeast?: number; atMost?: number }>>
  /** 同链上一环发生之后才轮得到它 */
  after?: string
  /** 它把这个府变成什么样 */
  shift: Partial<Record<RegionKey, number>>
  /** 相对权重。条件够了也未必就发生 */
  weight?: number
  /** 一件事不该年年发生。隔几年才能再来一次 */
  cooldown?: number
  /**
   * 编年史上怎么记。
   *
   * 只有真正会被人说起的事才写——「今年雨水少了些」不必记，
   * 「大旱，饿死了人」要记。玩家出生前的这些记录，
   * 构成了他睁开眼时这个世界已经有的历史。
   */
  chronicle?: string
}

