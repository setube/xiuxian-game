// 条件与效果
// ============================================================

export interface Condition {
  flag?: { key: string; equals?: FlagValue }
  attribute?: { key: AttributeKey; atLeast: number }
  knowledge?: string
  item?: string
  /** 年龄闭区间 */
  age?: { atLeast?: number; atMost?: number }
  /** 家境刻度闭区间。隐藏刻度，只在这里露面 */
  standing?: { atLeast?: number; atMost?: number }
  /** 某位家人是否在世 */
  family?: { id: string; alive: boolean }
  /**
   * 有没有某一层关系，那个人还在不在。
   *
   * 剧本必须能问「你还有爹吗」——否则孤儿会读到自己死去的父亲下地干活。
   * 这一条是关系网做出来之后，剧本层必须跟上的守门人。
   */
  bond?: { kind: Bond; alive?: boolean }
  /**
   * 这个府此刻的光景。
   *
   * 「世界事件改变条件，不直接替玩家决定结果」——这一行就是那个「条件」。
   * 旱灾把粮价推上去，然后「米贵了你家怎么办」这一卷才有资格发生；
   * 至于你家是卖地、借债还是把孩子送去当学徒，仍然是玩家自己选。
   */
  region?: Partial<Record<RegionKey, { atLeast?: number; atMost?: number }>>
  trade?: Trade
  /**
   * 这家人过的是什么日子。见 `content/living.ts`。
   *
   * 跟 `trade` 的区别是根本性的，而且这个区别是被穿帮逼出来的：
   * `trade` 是户籍——你生在哪一家；`living` 是生活——你实际过的日子。
   * 老乞丐捡去养大的孩子，`trade` 还是农户，`living` 是讨饭的。
   *
   * **写生活细节的正文一律问这一条，不问 `trade`。**
   * 「父亲在檐下修一把锄头」从前不问任何条件，于是皇子也读得到，
   * 那不是文案写错，是内容层把 `trade` 当成了默认真相。
   *
   * 两格各有一份真实内容在用，不是先摆好的阶梯：
   *
   * - `is` 精确到一种日子。`days.ts` 那几条下地割草的用它——
   *   「割了半晌草」这件事只有种地的人家有。
   * - `hasChore` 问的是「大人闲下来有没有一件摆弄得着的活」。
   *   `kin.ts` 的「北边」那一卷用它：那一卷要的不是农户，
   *   是一个檐下、一件活、一个能蹲在旁边看的孩子。宫里三样都没有。
   *
   * 用 `hasChore` 而不是把六种日子列成一串「或」，是因为列出来的那一串
   * 加一种出身就得回来改，而且没有任何机器会提醒——那正是这次要拆掉的东西。
   */
  living?: { is?: string; hasChore?: boolean }
  gender?: Gender
  stage?: LifeStage
}

/**
 * 状态变化的唯一表达方式。
 * 剧本只声明「发生了什么」，怎么落到 store 由 engine/effects.ts 统一结算。
 */
export type Effect =
  | { type: 'time'; years?: number; months?: number; days?: number }
  | { type: 'attribute'; key: AttributeKey; delta: number }
  | { type: 'flag'; key: string; value: FlagValue }
  | { type: 'place'; place: string }
  /**
   * 搬家。
   *
   * 跟 place 的区别：place 是「你此刻人在哪」，home 是「你家在哪」。
   * 抄家、削爵、逃荒之后，回家这个动作指向的地方就变了——
   * 只改 place 的话，收尾那一卷一句「你回到家」会把废太子送回东宫。
   */
  | { type: 'home'; place: string }
  | { type: 'realm'; realm: Realm }
  | { type: 'identity'; identity: string }
  /**
   * 换一种日子过。
   *
   * 跟 `identity` 并排放着，而它们**不是一回事**，这个分别是被内容逼出来的：
   * 削爵迁出京城的皇子 `identity` 是「庶人」，削藩搬家的王府世子是
   * 「寓公之子」，可这两个人过的是同一种日子（`fallen`）。反过来，
   * 同一场削爵之后开门走出去的和把门关上的，`identity` 都是「庶人」，
   * 过的日子却不一样。
   *
   * **身份是别人怎么称呼你，日子是你早上起来面对什么。**
   *
   * 值是 `content/living.ts` 里某一格的 `Living.id`。写下来的那一段
   * 不会被下一次覆盖，只会被封口——见 `character.liveAs`。
   */
  | { type: 'living'; living: string }
  /** 改写角色对自己某一面的看法 */
  | { type: 'aspect'; key: AspectKey; self: string | null }
  /** 别人对你的评说。只增不改，认知的错位就藏在这里 */
  | { type: 'claim'; key: AspectKey; source: string; text: string; doubt?: string }
  /**
   * 有人打量了你一眼。
   *
   * 跟 claim 的区别是根本性的：claim 是剧本作者写死的一句话，
   * observe 是**算出来的**——拿这个人的尺子去量你的真实属性，
   * 按他的判断力加上偏差，再按他的说话习惯选一档措辞。
   *
   * 所以同一个角色，先生说「记性极好」，炼气修士说「悟性一般」，
   * 宗门长老说「资质不错，悟性普通」。三句话都是真话，
   * 都来自同一份真实数据，只是量的东西和量的准头不同。
   *
   * 铁律：它只往认知层写，一个字也不碰真实属性。
   */
  | { type: 'observe'; observer: string }
  | { type: 'relation'; id: string; name: string; delta: number; note?: string }
  | {
      type: 'knowledge'
      id: string
      title: string
      /** null 表示只听过名字 */
      summary: string | null
      category: KnowledgeCategory
      /**
       * 他这一次离这件事有多近。不写就是「听说」。
       *
       * 只能往上走：亲眼见过之后，再听人说一嘴也不会退回「听说」。
       */
      contact?: Contact
      /**
       * 他这一次形成了什么样的解释。不写就按有没有 summary 定：
       * 有说法是「猜想」，没说法是「未理解」。
       *
       * **写 `未理解` 是有用的**：他知道有这么件事，可他说不出那是什么。
       */
      interpretation?: Interpretation
    }
  | { type: 'item'; id: string; name: string; count?: number; unit?: string; note?: string }
  | { type: 'chronicle'; text: string; tone?: InkTone }
  /** 家境涨落。隐藏刻度，不出回执——玩家该从叙事里读出来，不是从账单上 */
  | { type: 'household'; standing?: number; debt?: number }
  /**
   * 家人境况改写。alive 转 false 即此人不在了。
   *
   * ## `calls` 不是可有可无的一格
   *
   * 从前这里没有它，引擎那一行写的是 `people.meet(effect.id, effect.id, ...)`
   * ——**把内部 id 当成了玩家嘴里的称呼**。爹娘没露馅，因为出生那一刻
   * 就已经 `meet` 过，而 `meet()` 对已认识的人不改称呼；
   * 头一次出现的人就露了：人际面板上明晃晃写着 `sibling`。
   *
   * ## `born` 说的是「人口册上还没有这个人」
   *
   * 家里添的孩子是这一世中途生出来的，`beBorn` 那张网里没有他。
   * 不写这一格就只往认知层记一句 note，而人口册上是空的——
   * 于是「比你小几岁」那句话因为 `personOf` 是空而永远不显示，
   * 家里多了一张嘴 `household.members` 也数不出来。
   *
   * 它是显式的，不是「查不到就造一个」：id 打错一个字母的时候，
   * 后者会凭空生出一个人来，而没有任何东西会吭声。
   */
  | { type: 'family'; id: string; calls?: string; born?: boolean; alive?: boolean; note?: string }
  /**
   * 改写一个人的下落。
   *
   * 跟 family 的区别：family 说的是「我家那位怎么样了」，
   * person 说的是「这个人现在在哪、干什么、还在不在」——
   * 后者对世界上任何一个人都成立，跟他是不是你爹无关。
   *
   * 父亲离家做工不是把他删掉，是 `{ place: '青州某县', trade: '商队伙计' }`。
   * 他还在那儿，只是不在你眼前。
   */
  | {
      type: 'person'
      id: string
      place?: string
      trade?: string
      fate?: Fate
      health?: number
    }
  /**
   * 玩家认识了一个人，或者跟已经认识的人又亲近／疏远了一点。
   *
   * `calls` 是玩家此刻怎么称呼他——「渡口的青衫人」而不是他的名字。
   * 只在头一次遇见时需要写；对已经认识的人调好感，省掉它就行。
   *
   * 名字要另外由 `name: true` 才算知道，因为「认识一个人」和
   * 「知道他叫什么」本来就是两回事：你可以跟人打十年交道只知道他叫老周。
   */
  | { type: 'meet'; id: string; calls?: string; delta?: number; note?: string; name?: boolean }
  /**
   * 玩家得知了某人过去的一件事。
   *
   * 「原来爹年轻时去过北方」——那件事从他十八岁那年起就是真的，
   * 玩家今天才知道。这是人身上的「多年以后才明白」。
   */
  | { type: 'recall'; id: string; chapter: string }
  /**
   * 他抬头看了看外头。
   *
   * 世界状态在这里转成「玩家可观察到的现实」——
   * 不是 `grain = 138`，是「这阵子的粥稀了」。
   *
   * 一次只给一两处：给全了，玩家就能反推出精确的世界状态，
   * 那跟直接把数值摊开没有区别。
   */
  | { type: 'signs'; limit?: number }
  /**
   * 他去问了一个人。
   *
   * 跟 signs 的分别：那个是世界给他看的，这个是他自己去要的。
   * 但要来的不是正确答案，是**那个人的局部世界**——
   * 对方可能不知道、可能不肯说、可能自己就理解错了。
   */
  | { type: 'ask'; who: string; about: Topic }
  /**
   * 那一天，他把注意力放在了哪儿。
   *
   * 排在 `glance` 前面一层：**先问他有没有看见，再问他看成了什么。**
   * 从前这一层是一行阈值（`insight ≥ 34`），量出来三百个人全都看见了；
   * 现在由「心思细不细 + 那天他心里装着什么 + 路上是什么天」合起来掷，
   * 落在 `attention` 旗标上，三档：caught / glimpsed / missed。
   *
   * 最压着他的那件心事会印进正文，**三档都印**——他知道自己那天
   * 心不在焉，只是永远不会知道错过了什么。
   */
  | { type: 'attend' }
  /**
   * 山道上那个人：他看了片刻，心里有了个判断。
   *
   * 判断从他自己的见识长出来，而且**可能是错的**——
   * 错了也照样往下走。真相与认知分开存：
   * 世界记着 wounded-man = 修士，玩家记着 reading = 醉汉。
   */
  | { type: 'glance' }
  /**
   * 他做了一件事，世界回应他。
   *
   * 不看气运——用气运决定机缘成不成，那机缘就还是抽奖。
   * 看的是这个动作、这个人伤得多沉、这具身子骨、以及花了多少时间。
   */
  | { type: 'encounter'; approach: '扶' | '看' | '叫人' }
  /**
   * 庙前那册书：他翻了两页，认定它是什么。
   *
   * 跟 `glance` 是同一个位置的东西，验的却是相反的一种机缘——
   * 山道上的误读伸手就被戳破，**这一册的误读可以揣着走十年**。
   * 出身在这里直接塑造误读的形状：药铺的孩子看见方子，
   * 商户的孩子看见账，不认字的人只看见纸。
   */
  | { type: 'appraise' }
  /**
   * 他对那册书做了什么。
   *
   * 「是否在意」这一节刻意与他读成什么无关：把它当废纸的人照样可能
   * 顺手买下，看出不对劲的人也照样可能怕惹事走开。
   */
  | { type: 'book'; act: '买' | '翻' | '问' | '走' | '守' }
  /**
   * 多年以后，有人说出那册书真正的名字。
   *
   * 这一步才是这支机缘的终点——**抓住机会不等于当场获得答案**。
   * 它同时做两件事：给行囊里那件东西改名，
   * 以及把玩家那条错了很多年的认知**明确纠正**掉。
   */
  | { type: 'book-named' }
  /**
   * 跟走北路那个商旅谈一次。
   *
   * 这一条跟 `ask` 的区别是根本性的：`ask` 拿回来的是一段现成的话，
   * 这里拿回来的是**两个人的理解撞出来的结果**——
   * 商旅怎么理解修士、他肯说多少、玩家已经以为了什么、
   * 他听不听得出弦外之音，四样东西一起决定这一夜的结果。
   *
   * 而结果**不是「玩家的认知被改对」**。它可能是动摇、可能是多出一个
   * 并排放着的说法、可能是明确纠正，也可能是——最常见的那一种——
   * 他把真话塞回了自己原来那个框里，从此更自信，也更错。
   */
  | { type: 'hearsay' }
  /**
   * 这一段他去做了那件事，世界回应他。
   *
   * 这是玩家**第一次不是被事件叫出来**才行动的地方：没有人弹一卷剧本，
   * 是他自己决定今天上午干什么。
   *
   * 而绝大多数时候的结果是「没什么特别的」——那不是缺内容，是立场。
   * 每次行动都给知识给属性给奖励，那是操作游戏；
   * 真实的一天最常见的结果本来就是什么也没发生，
   * 也正因为如此，真的改变了什么的那些日子才显得要紧。
   */
  | { type: 'daily'; slot: '上午' | '下午' | '傍晚' }
  /**
   * 一天过完了，把这一天落进日录。
   *
   * 顺手回头看一眼有没有哪一天忽然想明白了——**这一步不出回执**。
   * 想起一件旧事本来就是安静的；弹出来就变成了发奖，
   * 而这套东西的全部立场就是它不发奖。
   */
  | { type: 'diary' }
  /**
   * 他读到一个机会。
   *
   * 头一句谁都读得到，那是这件事本来的样子；心里存着某个念头的人
   * 会多读出一句。而那一句不添信息，只添注意力——
   * 「那支商队要往很远的地方去」是他自己想到的，不是别人多告诉他的。
   *
   * **念头不得创造世界事实。** 机会出不出现只看世界，
   * 念头只改他怎么读它。
   */
  | { type: 'reading'; opening: string }
  /**
   * 他停下来重新掂量了一回。
   *
   * 念头平时是在一天一天的日子里慢慢长、慢慢退的。可有些经历
   * **本身就会让人当场重新想一遍**——走了一趟远路回来的那个晚上，
   * 家里病倒一个人的那阵子。这一条给那些时刻用。
   *
   * 它不发奖，也不弹框：跑一遍火种和反向火种，该涨的涨，该退的退。
   */
  | { type: 'reflect' }
  /**
   * 他打听了一回关于修行的消息。
   *
   * 多半什么也没听着。听着了也多半是假的——**而他分不出来**。
   * 修行的第一关不是学不会，是不知道去哪找。
   */
  | { type: 'ask-around' }
  /**
   * 他跑了一趟。
   *
   * 去镇上三天，去渡口两天，找先生问一句半天就回来了——
   * **寻找是一种人生行为，不是一个任务。** 而去了不代表能找着：
   * 今天没有船、那个人已经走了、有人提起一个名字、你找错了人。
   *
   * ## 天数不写在这里
   *
   * 这一格只管「跑的是哪一趟」，时间由同一批里的 `time` 推。
   * 两者都从 `Errand.days` 那一处取，剧本不手抄第二遍。
   *
   * 分开写不是啰嗦，是**两相结算的要求**：`time` 属上下文相、
   * 先跑；这一格属事实相、后跑。让它自己推时间的话，
   * 「一批效果是一个时刻」这条就破了，顺序又开始影响结果。
   */
  | { type: 'errand'; id: string }
  /**
   * 他跟着一条线索跑了一趟。
   *
   * 世界怎么回应，只看那地方到底是什么，不看他多想找到。
   */
  | { type: 'follow' }
  /**
   * 他站在门前。
   *
   * 收不收，他永远不知道是凭什么——那个人说了一句话，
   * 而**那句话他听不懂**。
   */
  | { type: 'knock'; enter: boolean }
  /**
   * 他跟一个修士照了个面。
   *
   * ## 跟 observe 的分别：这一格是两头的
   *
   * `observe` 只走一个方向——某个人打量了你，往认知层记一句他的话。
   * 这一格同时走两头：**他拿他的尺子量你，你拿你没有的尺子量他。**
   *
   *     他怎么看你　　落进 aspects.claims，只增不改
   *          ↕
   *     你怎么看他　　落进 knowledge，多半带着一个你看不见的 mistaken
   *
   * ## 他怎么待你，按他量到的数，不按真值
   *
   * 一个看不见资质的炼气修士量到你「悟性一般」，就随口应付两句走了——
   * 哪怕站在他跟前的是万里挑一的胚子。**看错的后果是真的**，
   * 而你这辈子不会知道为什么他那天没有多说一句。
   *
   * 铁律照旧：一个字也不碰真实属性，也不发任何东西。
   * 走到这一步他没有获得功法、境界或者资格，他只是见着了一个人。
   */
  | { type: 'meeting'; who: string }
  /**
   * 他决定肯跟你到哪一步。
   *
   * ## 「量到什么」和「愿意做什么」是两件事
   *
   * `meeting` 那一格算的是 `regard`——他量到的那个数。这一格算的是
   * **他拿那个数、按他自己的标准，决定要不要在你身上花工夫**。
   * 两者中间隔着三样东西，缺一样这一章就塌：
   *
   *     他量到了什么　　可能看错，而且他不知道自己看错了
   *     他在意什么　　　药庐那位一辈子不看资质，他看的是肯不肯守着
   *     他自己的处境　　有事在身的人不收徒，哪怕他看出你是块料
   *
   * 于是四种人生同时成立，而**玩家分不出自己是哪一种**：
   *
   *     资质好 · 他看不见 → 不教
   *     资质平 · 他看得准 → 他觉得你适合别的事 → 教一点
   *     资质好 · 他看得见 → 可他有自己的事 → 仍旧不教
   *     资质平 · 他看错了 → 教了 → 后来才发现不合适
   *
   * ## 一步一步地走，不跳档
   *
   * 不理会 → 搭话 → 使唤 → 带一段 → 教一点。**一次最多往上挪一格**，
   * 所以「第一次不教、第二次教一点、第三次才正经收下」是免费的：
   * 同一个人见三回，自然就是三格。
   *
   * 这一格**不牵师徒那条边**。走到「教一点」他仍旧不是你师父，
   * 界面上也不会跳出【师父：某某】——师承是关系一点一点长出来的，
   * 不是一个开关。
   */
  | { type: 'tutelage'; who: string }
  /**
   * 他真的教了那一点东西。
   *
   * 教的是一段话。**落进 knowledge 的是那段话本身，不是「学会了」**——
   * 他念了一遍，你记住了几个字，如此而已。
   *
   * 这一格还悄悄记下**是谁教的**，因为往后每一回打坐都要拿他的教法
   * 去对那样东西要的教法。对不上的时候，他念得越认真，
   * 你越笃定地往错地方使劲——见 `practice`。
   */
  | { type: 'teaching'; who: string; rite: string }
  /**
   * 你自己回去试着照做。
   *
   * 一次推不动就是推不动。**这一格最常见的结果是什么也没发生。**
   *
   * 一回打坐同时走两条轴，而这两条之间没有换算关系：
   *
   *     脑子里　听过 → 记住 → 明白
   *     身　上　没上手 ─┬→ 照着做 ─→ 摸着了 ─→ 拿得住
   *                     └→ 走岔了 ─┘
   *
   * 中间那个分叉是这一格最要紧的地方：**方向对但还没碰着的人，
   * 和方向根本错了的人，读到的是同一段话。** 而「什么也没发生」
   * 在每一格里长得都一样——背不全的人、背得滚瓜烂熟却一丝气感也没有的人、
   * 从第一天起就坐错了的人，看到的都是同一件事。
   */
  | { type: 'practice'; rite: string }
  /**
   * 世界在幕后掷一次骰，把结果写进旗标。
   *
   * 「机缘」不翻车的关键就在这里：山道上躺着的那个人是猎户、是修士、还是邪修，
   * 在你看见他之前就已经定了。你的选择改变的是自己撞上什么，
   * 不是把他变成对你有利的那一种。玩家永远看不到这一掷。
   */
  | { type: 'roll'; key: string; among: readonly { value: FlagValue; weight: number }[] }
  /**
   * 你终于认出手里这东西是什么。
   * 「多年以后才明白当年捡到的不是普通书」全靠它落地，
   * 所以它是少数几个会以朱砂回执报账的效果之一。
   */
  | { type: 'reveal'; item: string; name: string; note?: string }

