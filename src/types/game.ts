/** 底栏六个面板。第三层信息（认知）与第二层（状态）都从这里进。 */
export type PanelKey =
  'character' | 'inventory' | 'knowledge' | 'relations' | 'diary' | 'chronicle' | 'world'

/**
 * 日录里的一天。
 *
 * ## 日录不是编年，也不是日志
 *
 *     日录　我活过什么
 *     认知　我以为那是什么
 *     编年　什么真正成为了人生
 *
 * 三样东西各管一头，不许互相代替。编年只收真正改变了人生的节点；
 * 而一个人绝大多数的日子什么也没改变——**那些日子恰恰是他活过的证据**。
 *
 * ## 但光把原文存起来只是日志
 *
 * 「今天帮家里收了一下午麦子」单独看没有任何意义，
 * 存三百条也还是没有意义。
 *
 * 真正让一天变成回忆的，是**后来发生的事让它重新有了意义**：
 *
 *     十四岁那天写的是　　「姐姐最近总往镇上跑。」
 *     十几年后才明白的是　「原来她那一年是在为自己准备离家。」
 *
 * 所以 `lines` 是当年的原话，**永远不改**；
 * 后来想明白的事只往 `hindsight` 里追加。这跟知识条目
 * 只往 `history` 里追加、绝不抹掉旧说法，是同一个立场。
 */
export interface DayEntry {
  id: string
  at: GameTime
  /** 那天他做了什么、看见了什么。当年的原话，永远不改 */
  lines: readonly string[]
  /**
   * 这一天沾着哪些东西。
   *
   * 日后的新知识靠它把旧日子找回来——**没有标记的一天，
   * 再重要也没人想得起它**。写标记的时候要问：
   * 这一天里有什么，是多年以后可能被重新理解的？
   */
  tags: readonly string[]
  /** 后来才想明白的事。只追加，不覆盖原文 */
  hindsight?: readonly { at: GameTime; text: string }[]
}

/**
 * 一条「后来才明白」的规则。
 *
 * 它不修改历史，它给历史加一层新的解释——
 * **过去的事实 + 现在的新知识 = 新的意义。**
 */
export interface HindsightRule {
  id: string
  /** 得先有这条认知或旗标，他才可能回头想起来 */
  needs: readonly Condition[]
  /** 去找带这些标记的旧日子 */
  tags: readonly string[]
  /**
   * 至少要过几年才想得起来。
   *
   * 当场就明白的不叫「多年以后」，那叫当天的结果。
   * 这一条是这套系统的分寸所在。
   */
  after: number
  /** 那句话。写 `{years}` 会换成隔了多少年 */
  text: string
}
