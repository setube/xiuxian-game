export interface Choice {
  id: string
  label: string
  /** 朱砂标记：危险、异常，或再无回头路 */
  critical?: boolean
  /** 常驻于选项右侧的小字说明 */
  hint?: string
  /**
   * 条件不满足时的灰置理由。
   * 写了它，这条路就以「够不到」的样子留在选项里，让玩家知道此处有路；
   * 不写，条件不满足时整条选项隐去。
   */
  lockedHint?: string
  /** 选后留在正文中的回响文字；缺省则回响 label */
  echo?: string
  requires?: Condition[]
  effects?: Effect[]
  /** null 表示本卷终了 */
  next: string | null
}

/** 呈交给界面的选项：附带「此刻能不能选」与「要花掉多少时间」。 */
export interface ChoiceOption {
  choice: Choice
  locked: boolean
  /** 时间代价，如「三年」「半月」。不花时间的选项为 null */
  cost: string | null
}

export interface SceneNode {
  id: string
  /** 进入本节点即结算 */
  onEnter?: Effect[]
  /** 这件事本来的样子。谁都读得到，一个字不因人而异 */
  blocks: NarrativeBlock[]
  /**
   * 同一件事，他看见的不一样。
   *
   * ## 为什么不用 `branches` 做
   *
   * 换节点就是换事件。「遇见渡口那个人」若因为家里死过人而跳到另一节，
   * 那就是两段各写各的内容——写的时候是一件事的两种样子，
   * 改到第三次就是两件事了，而没有任何地方会吭声。
   *
   * 这一格要的是另一件事：**同一个节点，同一批选项，同一个去向。**
   * 变的只有他多看见的那一两句。
   *
   * ## 类型上就不可能变成分支
   *
   * 这里只有 `text`。没有 `effects`，没有 `next`，没有 `choices`——
   * 不是靠纪律拦着，是压根写不出来。**能用类型守住的就别拿门禁去守。**
   *
   * 剩下那半条纪律机器管不了，得作者自己守：
   * **只添注意力，不添信息。** 「你想起家里那年也是这样」可以，
   * 「你认出那是修士」不行——后者添的是世界事实，
   * 于是没死过人的孩子和死过人的孩子从此读到的是两个世界。
   *
   * ## 跟机会那一层的分工
   *
   * `Opening.readings` 由**念头**驱动：他心里存着想走的念头，
   * 才多读出「那支商队要往很远的地方去」。这一格由**人生事实**驱动——
   * `Condition` 里根本没有念头那一格，写不进来。
   *
   * 两条通路各管一边，因为它们回答的不是同一个问题：
   * 一个是「他想要什么」，一个是「他经历过什么」。经历过丧事的孩子
   * 站在江边，不需要先长出什么念头，才配多看那个人一眼。
   */
  seen?: readonly { requires: Condition[]; text: string }[]
  choices?: Choice[]
  /**
   * 按条件分流，自上而下取第一个满足的。
   *
   * 用在「同一个动作，结果取决于玩家不知道的事」：你上前查看倒在山道上的人，
   * 选项只有一条，但他是猎户还是邪修早已掷定，从这里分头走。
   */
  branches?: { requires: Condition[]; next: string }[]
  /** 无选项时自动续接的下一节点，用于把长段落切分成有呼吸的几节 */
  next?: string
}

export interface Scene {
  id: string
  title: string
  /** 起始节点 id */
  entry: string
  nodes: Record<string, SceneNode>
}

/** 场景库。跨卷跳转写作 `场景id#节点id`，省略 `#节点id` 即从该卷入口进。 */
export type SceneLibrary = Record<string, Scene>

